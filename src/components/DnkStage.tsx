"use client";

import { useCallback, useEffect, useRef, useState } from "react";

import { DnkPanel, type ПравкаГенов } from "@/components/DnkPanel";
import { downloadBlob } from "@/lib/format";
import { собратьСцены, перенумеровать } from "@/lib/dnk/гены";
import { архивДНК, имяАрхива, описаниеДНК } from "@/lib/dnk/файл";
import {
  ПРЕДЕЛ_ДЛИТЕЛЬНОСТИ,
  САМАЯ_КОРОТКАЯ_СЦЕНА,
  разрезатьНаСцены,
} from "@/lib/dnk/нарезка";
import {
  пустыеГены,
  type ВидПерехода,
  type ДНК,
  type КадрыСцены,
  type Переход,
  type СлотСцены,
  type СценаДНК,
} from "@/lib/dnk/types";
import { grabFrame } from "@/lib/video/capture";
import type { Analysis, VideoMeta } from "@/lib/types";

/*  ЗАПУСК И ПРАВКА ДНК.

    Здесь живут сама нарезка, ключевые кадры и ручные правки владельца.
    Экран (`DnkPanel`) только показывает — так его проще менять, когда
    подключим генерацию.                                              */

/** Отступ внутрь сцены, чтобы в кадр не попала смазанная склейка. */
const ОТСТУП_КАДРОВ = 3;

type Свойства = {
  videoRef: React.RefObject<HTMLVideoElement | null>;
  meta: VideoMeta | null;
  analysis: Analysis | null;
  готово: boolean;
  времяПлеера: number;
  onПеремотать: (время: number) => void;
  onДНК: (днк: ДНК | null) => void;
  onСообщение: (вид: "success" | "error" | "info", заголовок: string, текст?: string) => void;
};

export function DnkStage({
  videoRef,
  meta,
  analysis,
  готово,
  времяПлеера,
  onПеремотать,
  onДНК,
  onСообщение,
}: Свойства) {
  const [днк, setДНК] = useState<ДНК | null>(null);
  const [кадры, setКадры] = useState<Map<string, КадрыСцены>>(new Map());
  const [выбрана, setВыбрана] = useState<string | null>(null);
  const [занято, setЗанято] = useState(false);
  const [ход, setХод] = useState<{ доля: number; подпись: string } | null>(null);
  const [ошибка, setОшибка] = useState<string | null>(null);
  const [скачивается, setСкачивается] = useState(false);

  /*  Метка запуска вместо общего «отменить всё». React в разработке
      монтирует эффекты дважды: при прежнем устройстве первый проход
      гасился навсегда и нарезка замирала на первом проценте. Теперь у
      каждого прохода свой номер, и устаревший просто тихо выходит.  */
  const запускRef = useRef(0);
  const кадрыRef = useRef<Map<string, КадрыСцены>>(new Map());
  /*  Та же ДНК, но в ссылке: правки читают её отсюда и пересчитывают
      всё снаружи обновления состояния. Внутри обновления побочные
      действия выполняются дважды и кадры успевали устареть.        */
  const днкRef = useRef<ДНК | null>(null);

  /*  Снимок кадров одной сцены в полном разрешении ролика. Отступ от
      границы — чтобы не поймать смазанный кадр склейки.              */
  const снятьКадрыСцены = useCallback(
    async (сцена: СценаДНК, fps: number): Promise<КадрыСцены> => {
      const video = videoRef.current;
      if (!video) return { sceneId: сцена.id, первый: null, средний: null, последний: null };
      const отступ = ОТСТУП_КАДРОВ / (fps > 1 ? fps : 30);
      const длина = сцена.конец - сцена.начало;
      const безопасный = Math.min(отступ, Math.max(0, длина / 3));
      const точки: Array<[keyof Omit<КадрыСцены, "sceneId">, number]> = [
        ["первый", сцена.начало + безопасный],
        ["средний", (сцена.начало + сцена.конец) / 2],
        ["последний", сцена.конец - безопасный],
      ];
      const итог: КадрыСцены = {
        sceneId: сцена.id,
        первый: null,
        средний: null,
        последний: null,
      };
      for (const [ключ, время] of точки) {
        try {
          const снимок = await grabFrame(video, Math.max(0, время), "image/jpeg", 0.9, 1600);
          итог[ключ] = { время: снимок.time, url: снимок.url, blob: снимок.blob };
        } catch {
          /* один не снявшийся кадр не должен ронять всю ДНК */
        }
      }
      return итог;
    },
    [videoRef],
  );

  const забытьКадры = useCallback((набор: КадрыСцены | undefined) => {
    if (!набор) return;
    for (const ключ of ["первый", "средний", "последний"] as const) {
      const кадр = набор[ключ];
      if (кадр) URL.revokeObjectURL(кадр.url);
    }
  }, []);

  /*  Пересобрать кадры тех сцен, у которых они ещё не сняты или чьи
      границы сдвинулись.                                             */
  const обновитьКадры = useCallback(
    async (сцены: СценаДНК[], fps: number, заново?: Set<string>) => {
      const video = videoRef.current;
      if (!video) return;
      video.pause();
      const карта = new Map(кадрыRef.current);
      for (const сцена of сцены) {
        const было = карта.get(сцена.id);
        const надо = !было || (заново?.has(сцена.id) ?? false);
        if (!надо) continue;
        if (было) забытьКадры(было);
        const набор = await снятьКадрыСцены(сцена, fps);
        карта.set(сцена.id, набор);
        кадрыRef.current = карта;
        setКадры(new Map(карта));
      }
      /*  Сцены, которых больше нет (объединили, нарезали заново), —
          освобождаем их картинки, иначе память течёт.                */
      const живые = new Set(сцены.map((с) => с.id));
      for (const [id, набор] of карта) {
        if (!живые.has(id)) {
          забытьКадры(набор);
          карта.delete(id);
        }
      }
      кадрыRef.current = карта;
      setКадры(new Map(карта));
    },
    [videoRef, снятьКадрыСцены, забытьКадры],
  );

  const собрать = useCallback(async () => {
    const video = videoRef.current;
    if (!video || !meta || !meta.durationSec) return;
    const мой = (запускRef.current += 1);
    const устарел = () => запускRef.current !== мой;
    setЗанято(true);
    setОшибка(null);
    setХод({ доля: 0, подпись: "Ищем склейки… 0%" });
    try {
      video.pause();
      if (meta.durationSec > ПРЕДЕЛ_ДЛИТЕЛЬНОСТИ + 0.5) {
        onСообщение(
          "info",
          "Ролик длиннее минуты",
          "Частая выборка рассчитана на ролики до 60 секунд — нарезка займёт заметно дольше.",
        );
      }
      const итог = await разрезатьНаСцены(video, {
        длительность: meta.durationSec,
        fps: meta.fps || 30,
        onProgress: (доля, подпись) => setХод({ доля, подпись }),
        отменено: устарел,
      });
      if (устарел()) return;

      const сцены = перенумеровать(собратьСцены(итог.сцены, analysis));
      const свежая: ДНК = {
        версия: "1.0",
        источник: meta.fileName,
        длительность: meta.durationSec,
        ширина: meta.width,
        высота: meta.height,
        fps: meta.fps,
        сцены,
        переходы: итог.переходы,
        когда: new Date().toISOString(),
      };
      setДНК(свежая);
      setВыбрана(сцены[0]?.id ?? null);
      setХод({ доля: 1, подпись: "Снимаем ключевые кадры…" });
      await обновитьКадры(сцены, meta.fps || 30);
      if (устарел()) return;
      setЗанято(false);
      setХод(null);
      onСообщение(
        "success",
        "ДНК собрана",
        `${сцены.length} сцен · ${итог.переходы.length} переходов · ${итог.выборок} выборок`,
      );
    } catch (e) {
      if (устарел()) return;
      setЗанято(false);
      setХод(null);
      const текст = e instanceof Error ? e.message : "Неизвестная ошибка";
      setОшибка(текст);
      onСообщение("error", "ДНК не собралась", текст);
    }
  }, [videoRef, meta, analysis, обновитьКадры, onСообщение]);

  /*  Нарезаем, когда ролик готов. Новый ролик — новый проход; старый,
      если он ещё идёт, выходит сам по метке запуска.                */
  useEffect(() => {
    if (!готово || !meta?.durationSec) return;
    void собрать();
    return () => {
      запускRef.current += 1;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [готово, meta?.fileName, meta?.sizeBytes, meta?.durationSec]);

  useEffect(() => {
    днкRef.current = днк;
    onДНК(днк);
  }, [днк, onДНК]);

  /*  Уходим со страницы — освобождаем картинки кадров.             */
  useEffect(
    () => () => {
      for (const набор of кадрыRef.current.values()) забытьКадры(набор);
      кадрыRef.current = new Map();
    },
    [забытьКадры],
  );

  // ---------------- ручные правки ----------------

  /*  Граница с номером i — это конец сцены i-1 и начало сцены i.     */
  const сдвинутьГраницу = useCallback(
    (граница: number, дельта: number) => {
      const прежняя = днкRef.current;
      if (!прежняя) return;
      const сцены = прежняя.сцены.map((с) => ({ ...с }));
      if (граница <= 0 || граница >= сцены.length) return;
      const слева = сцены[граница - 1];
      const справа = сцены[граница];
      const новое = Number((справа.начало + дельта).toFixed(3));
      if (новое - слева.начало < САМАЯ_КОРОТКАЯ_СЦЕНА) return;
      if (справа.конец - новое < САМАЯ_КОРОТКАЯ_СЦЕНА) return;
      слева.конец = новое;
      справа.начало = новое;
      const переходы = прежняя.переходы.map((п, i) =>
        i === граница - 1 ? { ...п, время: новое } : п,
      );
      const обновлённые = перенумеровать(сцены);
      const свежая = { ...прежняя, сцены: обновлённые, переходы };
      днкRef.current = свежая;
      setДНК(свежая);
      void обновитьКадры(обновлённые, прежняя.fps || 30, new Set([слева.id, справа.id]));
    },
    [обновитьКадры],
  );

  /*  Объединение: граница с номером i исчезает, сцены i-1 и i
      становятся одной. Переход на этой границе тоже уходит.          */
  const объединить = useCallback(
    (граница: number) => {
      const прежняя = днкRef.current;
      {
        if (!прежняя) return;
        if (граница <= 0 || граница >= прежняя.сцены.length) return;
        const сцены = прежняя.сцены.map((с) => ({ ...с }));
        const слева = сцены[граница - 1];
        const справа = сцены[граница];
        слева.конец = справа.конец;
        /*  Гены правой сцены пропадают — оставляем те, что заполнены
            слева, а слоты объединяем: метка нужна, если была хоть в
            одной половине.                                           */
        слева.слоты = [...new Set([...слева.слоты, ...справа.слоты])] as СлотСцены[];
        сцены.splice(граница, 1);
        const переходы = прежняя.переходы.filter((_, i) => i !== граница - 1);
        const обновлённые = перенумеровать(сцены);
        const свежая = { ...прежняя, сцены: обновлённые, переходы };
        днкRef.current = свежая;
        setДНК(свежая);
        setВыбрана(слева.id);
        void обновитьКадры(обновлённые, прежняя.fps || 30, new Set([слева.id]));
      }
    },
    [обновитьКадры],
  );

  const разрезать = useCallback(
    (sceneId: string, время: number) => {
      const прежняя = днкRef.current;
      {
        if (!прежняя) return;
        const i = прежняя.сцены.findIndex((с) => с.id === sceneId);
        if (i < 0) return;
        const старая = прежняя.сцены[i];
        const точка = Number(время.toFixed(3));
        if (точка - старая.начало < САМАЯ_КОРОТКАЯ_СЦЕНА) return;
        if (старая.конец - точка < САМАЯ_КОРОТКАЯ_СЦЕНА) return;

        const первая: СценаДНК = { ...старая, конец: точка };
        const вторая: СценаДНК = {
          ...старая,
          id: `${старая.id}-b${Math.round(точка * 1000)}`,
          начало: точка,
          имя: `Сцена ${i + 2}`,
          /*  Новой половине достаются измеренные гены — они верны для
              обеих, — а вписанное руками остаётся слева.             */
          гены: { ...пустыеГены(), камера: старая.гены.камера, свет: старая.гены.свет },
        };
        const сцены = [...прежняя.сцены];
        сцены.splice(i, 1, первая, вторая);

        /*  Новый стык — резкая склейка с пометкой: его поставил
            человек, автоматика его не измеряла.                      */
        const новый: Переход = {
          вид: "склейка",
          время: точка,
          длительность: 0,
          проверьте: true,
          вручную: true,
        };
        const переходы = [...прежняя.переходы];
        переходы.splice(i, 0, новый);

        const обновлённые = перенумеровать(сцены);
        const свежая = { ...прежняя, сцены: обновлённые, переходы };
        днкRef.current = свежая;
        setДНК(свежая);
        setВыбрана(вторая.id);
        void обновитьКадры(обновлённые, прежняя.fps || 30, new Set([первая.id, вторая.id]));
      }
    },
    [обновитьКадры],
  );

  const сменитьПереход = useCallback((индекс: number, вид: ВидПерехода) => {
    setДНК((прежняя) =>
      прежняя
        ? {
            ...прежняя,
            переходы: прежняя.переходы.map((п, i) =>
              i === индекс ? { ...п, вид, проверьте: false, вручную: true } : п,
            ),
          }
        : прежняя,
    );
  }, []);

  const переключитьСлот = useCallback((sceneId: string, слот: СлотСцены) => {
    setДНК((прежняя) =>
      прежняя
        ? {
            ...прежняя,
            сцены: прежняя.сцены.map((с) =>
              с.id === sceneId
                ? {
                    ...с,
                    слоты: с.слоты.includes(слот)
                      ? с.слоты.filter((х) => х !== слот)
                      : [...с.слоты, слот],
                  }
                : с,
            ),
          }
        : прежняя,
    );
  }, []);

  const правитьГены = useCallback((правка: ПравкаГенов) => {
    setДНК((прежняя) =>
      прежняя
        ? {
            ...прежняя,
            сцены: прежняя.сцены.map((с) => {
              if (с.id !== правка.sceneId) return с;
              if (правка.поле === "имя") return { ...с, имя: правка.значение };
              return { ...с, гены: { ...с.гены, [правка.поле]: правка.значение } };
            }),
          }
        : прежняя,
    );
  }, []);

  const скачать = useCallback(async () => {
    if (!днк) return;
    setСкачивается(true);
    try {
      const архив = await архивДНК(днк, кадрыRef.current);
      downloadBlob(архив, имяАрхива(днк.источник));
      onСообщение(
        "success",
        "Файл ДНК готов",
        `${днк.сцены.length} сцен · dnk.json и кадры внутри архива`,
      );
    } catch (e) {
      onСообщение(
        "error",
        "Архив не собрался",
        e instanceof Error ? e.message : "Неизвестная ошибка",
      );
    } finally {
      setСкачивается(false);
    }
  }, [днк, onСообщение]);

  const пересобрать = useCallback(() => {
    void собрать();
  }, [собрать]);

  if (!meta) return null;

  return (
    <DnkPanel
      днк={днк}
      кадры={кадры}
      выбрана={выбрана}
      занято={занято}
      ход={ход}
      ошибка={ошибка}
      времяПлеера={времяПлеера}
      onВыбрать={setВыбрана}
      onПеремотать={onПеремотать}
      onСдвинутьГраницу={сдвинутьГраницу}
      onОбъединить={объединить}
      onРазрезать={разрезать}
      onПереход={сменитьПереход}
      onСлот={переключитьСлот}
      onГены={правитьГены}
      onСкачать={() => void скачать()}
      скачивается={скачивается}
      onПересобрать={пересобрать}
    />
  );
}

/*  Короткая выжимка для истории разборов — без картинок.             */
export function днкДляИстории(днк: ДНК | null) {
  return днк ? описаниеДНК(днк) : null;
}
