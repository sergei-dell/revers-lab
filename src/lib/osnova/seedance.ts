/*  ПЕРЕХОДНИК К ГЕНЕРАТОРУ.

    Seedance пока не подключён: владелец генерирует руками на сайте.
    Но место под подключение нужно уже сейчас, иначе потом придётся
    трогать весь экран. Вся связь с генератором сводится к одной
    функции: отдать основу, картинки по порядку, шаблон и настройки —
    получить ссылку на готовое видео.

    Когда появится доступ, меняется только тело `сгенерировать`;
    экран, кнопки и оценка остаются как есть.                        */

export type НастройкиГенерации = {
  /** Соотношение сторон, как «9:16». */
  формат: string;
  /** Длительность в секундах — берётся из ролика. */
  секунды: number;
  /** Какой моделью генерируем. */
  модель: string;
};

export type ЗаданиеГенерации = {
  /** Видео-основа: адрес, по которому её можно скачать. */
  основа: string;
  /** Картинки строго по порядку @image1…N. */
  картинки: string[];
  шаблон: string;
  настройки: НастройкиГенерации;
};

export type ИтогГенерации =
  | { готово: true; видео: string }
  | { готово: false; почему: string };

/** Подключён ли генератор. Пока — нет, и экран об этом честно говорит. */
export function генераторПодключён(): boolean {
  return false;
}

export const ПОЧЕМУ_НЕ_ПОДКЛЮЧЁН = "Генератор не подключён";

export async function сгенерировать(_задание: ЗаданиеГенерации): Promise<ИтогГенерации> {
  void _задание;
  /*  Заглушка. Настоящая реализация отправит задание в Seedance и
      вернёт ссылку на готовое видео.                               */
  return { готово: false, почему: ПОЧЕМУ_НЕ_ПОДКЛЮЧЁН };
}

/** Подсказка настроек под кнопкой генерации. */
export function подсказкаНастроек(н: НастройкиГенерации): string {
  return `${н.формат} · ${н.секунды.toFixed(1)} сек · ${н.модель}`;
}
