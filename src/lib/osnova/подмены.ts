/** Строка для списка «загрузите в этом порядке». */
export type СтрокаЗагрузки = { метка: string; что: string };

export function порядокЗагрузки(подмены: Подмена[]): СтрокаЗагрузки[] {
  const номера = номераКартинок(подмены);
  const список: СтрокаЗагрузки[] = [
    { метка: "@video1", что: "видео-основа (кнопка в блоке 1)" },
  ];
  for (const п of подмены) {
    if (!п.включена || !п.скартинкой) continue;
    список.push({ метка: `@image${номера[п.ключ]}`, что: ЧТО_ЗА_ФОТО[п.ключ] });
  }
  return список;
}

/*  То, что уходит в пакет для Claude файлом `что-меняем.json`.      */
export type ЧтоМеняем = {
  фишка: string;
  пункты: Array<{
    ключ: КлючПодмены;
    имя: string;
    включён: boolean;
    image: number | null;
    значение: string | null;
  }>;
};

export function чтоМеняем(подмены: Подмена[], фишка: string): ЧтоМеняем {
  const номера = номераКартинок(подмены);
  return {
    фишка: фишка.trim(),
    пункты: подмены.map((п) => ({
      ключ: п.ключ,
      имя: п.имя,
      включён: п.включена,
      image: п.включена && п.скартинкой ? (номера[п.ключ] ?? null) : null,
      значение: п.значение?.trim() || null,
    })),
  };
}
