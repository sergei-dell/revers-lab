/** Номера @image по порядку включённых пунктов с картинкой. */
export type НомераКартинок = Partial<Record<КлючПодмены, number>>;

export function номераКартинок(подмены: Подмена[]): НомераКартинок {
  const номера: НомераКартинок = {};
  let n = 0;
  for (const п of подмены) {
    if (п.включена && п.скартинкой) {
      n += 1;
      номера[п.ключ] = n;
    }
  }
  return номера;
}

export function включена(подмены: Подмена[], ключ: КлючПодмены): boolean {
  return Boolean(подмены.find((п) => п.ключ === ключ)?.включена);
}

export function значение(подмены: Подмена[], ключ: КлючПодмены): string {
  return (подмены.find((п) => п.ключ === ключ)?.значение ?? "").trim();
}

