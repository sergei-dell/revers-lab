import type { ДНКдляИстории } from "@/lib/dnk/types";
import type { РазборОсновы } from "@/lib/osnova/основа";
import { чтоМеняем, type Подмена } from "@/lib/osnova/подмены";
import { времяМетки, собратьШаблон, type Момент } from "@/lib/osnova/шаблон";

/*  ПАКЕТ ДЛЯ CLAUDE.

    Пока шаблон пишет человек через чат, Claude нужно отдать всё разом
    одним архивом: видео-основу, раскадровку, кадры, ДНК, фишку, что
    меняем, заготовку шаблона и саму задачу. Тот же набор уходит и по
    API, когда режим переключат на автоматический, — поэтому собирается
    он здесь, в одном месте.                                         */

/** Больше этого размера видео в чат не кладём — берём запасную. */
export const ПРЕДЕЛ_ВИДЕО = 20 * 1024 * 1024;

export type КадрПакета = {
  имя: string;
  время: number;
  blob: Blob;
};

export type СоставПакета = {
  разбор: РазборОсновы;
  фишка: string;
  замок: string;
  подмены: Подмена[];
  моменты: Момент[];
  баги: string[];
  днк: ДНКдляИстории | null;
  /** Смены движения из разбора — секунды от начала. */
  смены: number[];
  раскадровка: Blob | null;
  кадры: КадрПакета[];
  /** Текст «ПРОЧТИ-claude.md» как есть. */
  прочти: string;
  /** Видео-основа и её имя внутри архива. */
  видео: { имя: string; blob: Blob } | null;
};

/*  `фишка.txt` — всё, что человек знает о ролике словами: сама фишка,
    что нельзя трогать, моменты и записанные баги прошлых попыток.   */
export function файлФишки(состав: СоставПакета): string {
  const с = состав;
  const строки: string[] = [];
  строки.push("ФИШКА");
  строки.push(с.фишка.trim() || "(не заполнено — опишите одной строкой, в чём соль ролика)");
  строки.push("");
  строки.push("ЧТО В КАДРЕ НЕЛЬЗЯ МЕНЯТЬ");
  строки.push(с.замок.trim() || "(не заполнено)");

  if (с.моменты.length) {
    строки.push("");
    строки.push("МОМЕНТЫ");
    for (const м of с.моменты) {
      строки.push(`${времяМетки(м.время)} — ${м.что}${м.фишка ? "   ← фишка" : ""}`);
    }
  }

  if (с.смены.length) {
    строки.push("");
    строки.push("СМЕНЫ ДВИЖЕНИЯ (нашёл РЕВЕРС)");
    строки.push(с.смены.map((т) => времяМетки(т)).join(", "));
  }

  /*  Баги идут последними и заметно: Claude должен превратить каждый
      в отдельное правило, иначе та же ошибка повторится.           */
  if (с.баги.length) {
    строки.push("");
    строки.push("БАГИ ПРОШЛОЙ ГЕНЕРАЦИИ");
    строки.push("Каждый пункт — правило в нужном блоке шаблона и строка в NEGATIVES.");
    for (const б of с.баги) строки.push(`- ${б}`);
  }

  return строки.join("\n");
}

export function имяПакета(имяРолика: string): string {
  const основа = имяРолика.replace(/\.[^.]+$/, "").slice(0, 48).trim() || "ролик";
  return `пакет-${основа}.zip`;
}

/*  Какую основу класть в архив: большую, пока она влезает в чат, иначе
    запасную.                                                        */
export function какуюОснову(разбор: РазборОсновы): { файл: string; запасная: boolean } {
  return разбор.большая.байт > ПРЕДЕЛ_ВИДЕО
    ? { файл: разбор.запасная.файл, запасная: true }
    : { файл: разбор.большая.файл, запасная: false };
}

export async function собратьПакет(состав: СоставПакета): Promise<Blob> {
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();

  if (состав.видео) zip.file(состав.видео.имя, состав.видео.blob);
  if (состав.раскадровка) zip.file("раскадровка.jpg", состав.раскадровка);

  const папкаКадров = zip.folder("кадры");
  for (const к of состав.кадры) папкаКадров?.file(к.имя, к.blob);

  /*  ДНК кладём в том же виде, что и в «Скачать ДНК», плюс смены
      движения с таймкодами — Claude расставляет по ним якоря.      */
  const днк = {
    ...(состав.днк ?? { версия: "1.0", сцен: 0, сцены: [] }),
    длительность: состав.разбор.исходник.длительность,
    смены_движения: состав.смены.map((т) => ({ сек: Number(т.toFixed(2)), метка: времяМетки(т) })),
  };
  zip.file("днк.json", JSON.stringify(днк, null, 2));

  zip.file("фишка.txt", файлФишки(состав));
  zip.file(
    "что-меняем.json",
    JSON.stringify(чтоМеняем(состав.подмены, состав.фишка), null, 2),
  );
  zip.file(
    "заготовка-шаблона.txt",
    собратьШаблон({
      фишка: состав.фишка,
      замок: состав.замок,
      моменты: состав.моменты,
      подмены: состав.подмены,
      баги: состав.баги,
    }),
  );
  zip.file("ПРОЧТИ-claude.md", состав.прочти);

  return zip.generateAsync({ type: "blob" });
}
