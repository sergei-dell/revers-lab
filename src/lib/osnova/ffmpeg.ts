import { spawn } from "node:child_process";

/*  FFMPEG ВНУТРИ ПРОЕКТА.

    Системный ffmpeg не предполагаем: на чужой машине его может не быть
    или он будет собран без нужных фильтров. Берём тот, что приехал
    пакетом `ffmpeg-static` — один и тот же на всех машинах.          */

const путьFfmpeg = require("ffmpeg-static") as string | null;

export function ffmpegЕсть(): boolean {
  return Boolean(путьFfmpeg);
}

export type ЗапускИтог = {
  код: number;
  вывод: string;
};

/*  Запуск ffmpeg. Весь разговор ffmpeg ведёт в stderr — и ошибки, и
    сведения о файле, поэтому собираем именно его.                   */
export function запуститьFfmpeg(
  доводы: string[],
  опции: { срокМс?: number; наВыход?: (кусок: Buffer) => void } = {},
): Promise<ЗапускИтог> {
  if (!путьFfmpeg) {
    return Promise.reject(new Error("ffmpeg не найден — переустановите зависимости проекта"));
  }
  const срок = опции.срокМс ?? 120_000;
  return new Promise((готово, беда) => {
    const процесс = spawn(путьFfmpeg, доводы, { stdio: ["ignore", "pipe", "pipe"] });
    let вывод = "";
    let закрыт = false;

    const часы = setTimeout(() => {
      закрыт = true;
      процесс.kill("SIGKILL");
      беда(new Error("ffmpeg не уложился в отведённое время"));
    }, срок);

    процесс.stdout.on("data", (кусок: Buffer) => опции.наВыход?.(кусок));
    процесс.stderr.on("data", (кусок: Buffer) => {
      /*  Вывод бывает длинным; держим только хвост — он нужен лишь
          для разбора сведений и для текста ошибки.                 */
      вывод = (вывод + кусок.toString()).slice(-20_000);
    });
    процесс.on("error", (е) => {
      if (закрыт) return;
      clearTimeout(часы);
      беда(е);
    });
    процесс.on("close", (код) => {
      if (закрыт) return;
      clearTimeout(часы);
      готово({ код: код ?? -1, вывод });
    });
  });
}

export type СведенияРолика = {
  ширина: number;
  высота: number;
  длительность: number;
  fps: number;
};

/*  Что за ролик нам дали. Разбираем обычный вывод ffmpeg -i: отдельный
    ffprobe тянуть не стали, лишняя зависимость ради тех же цифр.    */
export async function сведенияРолика(файл: string): Promise<СведенияРолика> {
  const { вывод } = await запуститьFfmpeg(["-hide_banner", "-i", файл], { срокМс: 30_000 });

  const размер = /,\s(\d{2,5})x(\d{2,5})[\s,]/.exec(вывод);
  const время = /Duration:\s(\d+):(\d+):(\d+\.\d+)/.exec(вывод);
  const частота = /(\d+(?:\.\d+)?)\sfps/.exec(вывод);

  if (!размер) throw new Error("Не удалось прочитать размер кадра — это точно видеофайл?");

  const длительность = время
    ? Number(время[1]) * 3600 + Number(время[2]) * 60 + Number(время[3])
    : 0;

  return {
    ширина: Number(размер[1]),
    высота: Number(размер[2]),
    длительность: Number(длительность.toFixed(3)),
    fps: частота ? Number(частота[1]) : 30,
  };
}

export type Рамка = { x: number; y: number; w: number; h: number };

/*  ГДЕ ИНТЕРФЕЙС.

    Запись экрана из Instagram или TikTok сверху и снизу обрастает
    неподвижными полосами: шапка, подписи, кнопки, субтитры. Их видно
    по тому, что строки пикселей там не меняются от кадра к кадру,
    пока вся остальная картинка живёт.

    Считаем так: берём десяток кадров в сером и низком разрешении,
    по каждой строке смотрим, насколько она менялась во времени, и
    отрезаем сверху и снизу подряд идущие «мёртвые» строки.          */
const ВЫСОТА_РАЗБОРА = 192;
const КАДРОВ_НА_РАЗБОР = 12;

export async function найтиРамку(
  файл: string,
  сведения: СведенияРолика,
): Promise<{ рамка: Рамка; нашли: boolean }> {
  const целиком: Рамка = { x: 0, y: 0, w: сведения.ширина, h: сведения.высота };
  if (!сведения.длительность) return { рамка: целиком, нашли: false };

  const вы = ВЫСОТА_РАЗБОРА;
  const ши = Math.max(8, Math.round((сведения.ширина * вы) / сведения.высота / 2) * 2);
  const шаг = сведения.длительность / (КАДРОВ_НА_РАЗБОР + 1);

  const куски: Buffer[] = [];
  const { код } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-i",
      файл,
      "-vf",
      `fps=${(1 / шаг).toFixed(4)},scale=${ши}:${вы}:flags=bilinear,format=gray`,
      "-frames:v",
      String(КАДРОВ_НА_РАЗБОР),
      "-f",
      "rawvideo",
      "-",
    ],
    { срокМс: 90_000, наВыход: (к) => куски.push(к) },
  );
  if (код !== 0) return { рамка: целиком, нашли: false };

  const всё = Buffer.concat(куски);
  const размерКадра = ши * вы;
  const кадров = Math.floor(всё.length / размерКадра);
  if (кадров < 3) return { рамка: целиком, нашли: false };

  /*  Насколько строка шевелится: средний разброс яркости во времени. */
  const шевеление = new Float64Array(вы);
  for (let y = 0; y < вы; y += 1) {
    let сумма = 0;
    for (let x = 0; x < ши; x += 2) {
      let мин = 255;
      let макс = 0;
      for (let к = 0; к < кадров; к += 1) {
        const v = всё[к * размерКадра + y * ши + x];
        if (v < мин) мин = v;
        if (v > макс) макс = v;
      }
      сумма += макс - мин;
    }
    шевеление[y] = сумма / Math.ceil(ши / 2);
  }

  /*  Порог считаем от срединной строки, а не от самой живой. У ролика
      со спокойной картинкой самая живая строка задирает порог, и под
      нож уходит половина кадра; срединная строка показывает, как
      шевелится ролик вообще.                                        */
  const ряд = [...шевеление].sort((a, b) => a - b);
  const срединная = ряд[Math.floor(ряд.length / 2)];
  if (срединная < 3) return { рамка: целиком, нашли: false };
  const порог = Math.max(2.5, срединная * 0.25);

  let сверху = 0;
  while (сверху < вы && шевеление[сверху] < порог) сверху += 1;
  let снизу = вы - 1;
  while (снизу > сверху && шевеление[снизу] < порог) снизу -= 1;

  /*  Полосу шире половины кадра не режем: скорее всего ошиблись, а
      не у ролика половина — интерфейс.                             */
  if (сверху > вы * 0.4 || вы - 1 - снизу > вы * 0.4) {
    return { рамка: целиком, нашли: false };
  }

  const кВысоте = сведения.высота / вы;
  const y = Math.round((сверху * кВысоте) / 2) * 2;
  const низ = Math.round(((снизу + 1) * кВысоте) / 2) * 2;
  const h = Math.max(2, низ - y);
  const нашли = y > 0 || h < сведения.высота;

  return {
    рамка: { x: 0, y, w: сведения.ширина, h },
    нашли,
  };
}

/*  ЧИСТАЯ ОСНОВА. Обрезаем интерфейс, убираем шум записи экрана,
    поднимаем резкость и растягиваем до нужного размера. Длинная
    сторона кадра задаётся снаружи: вертикальный ролик идёт в
    1080×1920, горизонтальный — наоборот.                           */
export type РазмерОсновы = { ширина: number; высота: number };

export async function собратьОснову(
  вход: string,
  выход: string,
  рамка: Рамка,
  размер: РазмерОсновы,
): Promise<void> {
  const фильтры = [
    `crop=${рамка.w}:${рамка.h}:${рамка.x}:${рамка.y}`,
    "hqdn3d=3:3:6:6",
    `scale=${размер.ширина}:${размер.высота}:force_original_aspect_ratio=decrease:flags=lanczos`,
    `pad=${размер.ширина}:${размер.высота}:(ow-iw)/2:(oh-ih)/2:black`,
    "unsharp=5:5:1.0",
  ].join(",");

  const { код, вывод } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-y",
      "-i",
      вход,
      "-vf",
      фильтры,
      "-r",
      "30",
      "-c:v",
      "libx264",
      "-profile:v",
      "high",
      "-preset",
      "slow",
      "-crf",
      "14",
      "-pix_fmt",
      "yuv420p",
      "-movflags",
      "+faststart",
      "-c:a",
      "aac",
      "-b:a",
      "192k",
      выход,
    ],
    { срокМс: 110_000 },
  );
  if (код !== 0) {
    throw new Error(`Не удалось собрать основу: ${вывод.split("\n").slice(-3).join(" ").trim()}`);
  }
}
