import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";

/*  FFMPEG ВНУТРИ ПРОЕКТА.

    Системный ffmpeg не предполагаем: на чужой машине его может не быть
    или он будет собран без нужных фильтров. Берём тот, что приехал
    пакетом `ffmpeg-static` — один и тот же на всех машинах.          */

/*  Где лежит ffmpeg.

    Пакет `ffmpeg-static` отдаёт путь, посчитанный от своего файла. Под
    сборщиком Next этот файл переезжает, и путь превращается в
    несуществующий «/ROOT/node_modules/...». Поэтому сначала ищем
    бинарник рядом с проектом и только потом верим пакету.          */
function найтиFfmpeg(): string | null {
  const корень = process.cwd();
  const имя = process.platform === "win32" ? "ffmpeg.exe" : "ffmpeg";
  const где = [
    path.join(корень, "node_modules", "ffmpeg-static", имя),
    path.join(корень, "..", "node_modules", "ffmpeg-static", имя),
  ];
  for (const путь of где) {
    try {
      if (existsSync(путь)) return путь;
    } catch {
      /* ищем дальше */
    }
  }
  try {
    const изПакета = require("ffmpeg-static") as string | null;
    if (изПакета && existsSync(изПакета)) return изПакета;
  } catch {
    /* пакет не установлен */
  }
  return null;
}

const путьFfmpeg = найтиFfmpeg();

export function ffmpegЕсть(): boolean {
  return Boolean(путьFfmpeg);
}

export type ЗапускИтог = {
  код: number;
  вывод: string;
  /*  Времена кадров из showinfo. Собираются на лету: весь вывод мы не
      храним, и у длинного ролика ранние строки иначе теряются.      */
  времена: number[];
};

/*  Запуск ffmpeg. Весь разговор ffmpeg ведёт в stderr — и ошибки, и
    сведения о файле, поэтому собираем именно его.                   */
export function запуститьFfmpeg(
  доводы: string[],
  опции: { срокМс?: number; наВыход?: (кусок: Buffer) => void; времена?: boolean } = {},
): Promise<ЗапускИтог> {
  if (!путьFfmpeg) {
    return Promise.reject(new Error("ffmpeg не найден — переустановите зависимости проекта"));
  }
  const срок = опции.срокМс ?? 120_000;
  return new Promise((готово, беда) => {
    const процесс = spawn(путьFfmpeg, доводы, { stdio: ["ignore", "pipe", "pipe"] });
    let вывод = "";
    let закрыт = false;
    const времена: number[] = [];
    /*  Строка с временем может разорваться между кусками — держим
        хвост до следующего куска.                                  */
    let хвост = "";

    const часы = setTimeout(() => {
      закрыт = true;
      процесс.kill("SIGKILL");
      беда(new Error("ffmpeg не уложился в отведённое время"));
    }, срок);

    процесс.stdout.on("data", (кусок: Buffer) => опции.наВыход?.(кусок));
    процесс.stderr.on("data", (кусок: Buffer) => {
      const текст = кусок.toString();
      if (опции.времена) {
        const весь = хвост + текст;
        for (const м of весь.matchAll(/pts_time:([\d.]+)/g)) {
          const т = Number(м[1]);
          if (Number.isFinite(т)) времена.push(Number(т.toFixed(2)));
        }
        хвост = весь.slice(-40);
      }
      /*  Вывод бывает длинным; держим только хвост — он нужен лишь
          для разбора сведений и для текста ошибки.                 */
      вывод = (вывод + текст).slice(-20_000);
    });
    процесс.on("error", (е) => {
      if (закрыт) return;
      clearTimeout(часы);
      беда(е);
    });
    процесс.on("close", (код) => {
      if (закрыт) return;
      clearTimeout(часы);
      готово({ код: код ?? -1, вывод, времена });
    });
  });
}

export type СведенияРолика = {
  ширина: number;
  высота: number;
  длительность: number;
  fps: number;
};

/*  Что за ролик нам дали. Разбираем обычный вывод ffmpeg -i: отдельный
    ffprobe тянуть не стали, лишняя зависимость ради тех же цифр.    */
export async function сведенияРолика(файл: string): Promise<СведенияРолика> {
  const { вывод } = await запуститьFfmpeg(["-hide_banner", "-i", файл], { срокМс: 30_000 });

  const размер = /,\s(\d{2,5})x(\d{2,5})[\s,]/.exec(вывод);
  const время = /Duration:\s(\d+):(\d+):(\d+\.\d+)/.exec(вывод);
  const частота = /(\d+(?:\.\d+)?)\sfps/.exec(вывод);

  if (!размер) throw new Error("Не удалось прочитать размер кадра — это точно видеофайл?");

  const длительность = время
    ? Number(время[1]) * 3600 + Number(время[2]) * 60 + Number(время[3])
    : 0;

  return {
    ширина: Number(размер[1]),
    высота: Number(размер[2]),
    длительность: Number(длительность.toFixed(3)),
    fps: частота ? Number(частота[1]) : 30,
  };
}

export type Рамка = { x: number; y: number; w: number; h: number };

/*  ГДЕ ИНТЕРФЕЙС.

    Запись экрана из Instagram или TikTok сверху и снизу обрастает
    неподвижными полосами: шапка, подписи, кнопки, субтитры. Их видно
    по тому, что строки пикселей там не меняются от кадра к кадру,
    пока вся остальная картинка живёт.

    Считаем так: берём десяток кадров в сером и низком разрешении,
    по каждой строке смотрим, насколько она менялась во времени, и
    отрезаем сверху и снизу подряд идущие «мёртвые» строки.          */
const ВЫСОТА_РАЗБОРА = 192;
const КАДРОВ_НА_РАЗБОР = 12;

/*  ЧЁРНЫЕ ПОЛЯ. Их отдаёт сам ffmpeg фильтром cropdetect: вертикальный
    ролик, вложенный в горизонтальный файл, обрастает полями по бокам, и
    эти поля надо срезать всегда — в отличие от неподвижных плашек,
    которые мы только предлагаем.                                    */
export async function найтиЧёрныеПоля(
  файл: string,
  сведения: СведенияРолика,
): Promise<Рамка | null> {
  const старт = Math.min(1, Math.max(0, сведения.длительность / 4));
  const { код, вывод } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-ss",
      старт.toFixed(2),
      "-i",
      файл,
      "-vf",
      "cropdetect=limit=24:round=2:reset=0",
      "-frames:v",
      "60",
      "-f",
      "null",
      "-",
    ],
    { срокМс: 90_000 },
  );
  if (код !== 0) return null;

  let последняя: Рамка | null = null;
  for (const м of вывод.matchAll(/crop=(\d+):(\d+):(\d+):(\d+)/g)) {
    последняя = { w: Number(м[1]), h: Number(м[2]), x: Number(м[3]), y: Number(м[4]) };
  }
  if (!последняя) return null;

  /*  Не верим подсказке, если она съедает больше половины кадра или
      выходит за его край: лучше оставить поля, чем срезать картинку. */
  const { ширина, высота } = сведения;
  if (
    последняя.w < ширина * 0.4 ||
    последняя.h < высота * 0.4 ||
    последняя.x + последняя.w > ширина ||
    последняя.y + последняя.h > высота
  ) {
    return null;
  }
  const есть = последняя.w < ширина || последняя.h < высота;
  return есть ? последняя : null;
}

export async function найтиРамку(
  файл: string,
  сведения: СведенияРолика,
): Promise<{ рамка: Рамка; нашли: boolean }> {
  const целиком: Рамка = { x: 0, y: 0, w: сведения.ширина, h: сведения.высота };
  if (!сведения.длительность) return { рамка: целиком, нашли: false };

  /*  Сначала срезаем чёрные поля: дальше неподвижные плашки ищем уже
      внутри самой картинки, иначе поля сами выглядят как плашки.    */
  const поля = await найтиЧёрныеПоля(файл, сведения);
  const начальная: Рамка = поля ?? целиком;

  const вы = ВЫСОТА_РАЗБОРА;
  const ши = Math.max(8, Math.round((начальная.w * вы) / начальная.h / 2) * 2);
  const шаг = сведения.длительность / (КАДРОВ_НА_РАЗБОР + 1);

  const куски: Buffer[] = [];
  const { код } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-i",
      файл,
      "-vf",
      `crop=${начальная.w}:${начальная.h}:${начальная.x}:${начальная.y},fps=${(1 / шаг).toFixed(4)},scale=${ши}:${вы}:flags=bilinear,format=gray`,
      "-frames:v",
      String(КАДРОВ_НА_РАЗБОР),
      "-f",
      "rawvideo",
      "-",
    ],
    { срокМс: 90_000, наВыход: (к) => куски.push(к) },
  );
  if (код !== 0) return { рамка: начальная, нашли: Boolean(поля) };

  const всё = Buffer.concat(куски);
  const размерКадра = ши * вы;
  const кадров = Math.floor(всё.length / размерКадра);
  if (кадров < 3) return { рамка: начальная, нашли: Boolean(поля) };

  /*  Насколько строка шевелится: средний разброс яркости во времени. */
  const шевеление = new Float64Array(вы);
  for (let y = 0; y < вы; y += 1) {
    let сумма = 0;
    for (let x = 0; x < ши; x += 2) {
      let мин = 255;
      let макс = 0;
      for (let к = 0; к < кадров; к += 1) {
        const v = всё[к * размерКадра + y * ши + x];
        if (v < мин) мин = v;
        if (v > макс) макс = v;
      }
      сумма += макс - мин;
    }
    шевеление[y] = сумма / Math.ceil(ши / 2);
  }

  /*  Порог считаем от срединной строки, а не от самой живой. У ролика
      со спокойной картинкой самая живая строка задирает порог, и под
      нож уходит половина кадра; срединная строка показывает, как
      шевелится ролик вообще.                                        */
  const ряд = [...шевеление].sort((a, b) => a - b);
  const срединная = ряд[Math.floor(ряд.length / 2)];
  if (срединная < 3) return { рамка: начальная, нашли: Boolean(поля) };
  const порог = Math.max(2.5, срединная * 0.25);

  let сверху = 0;
  while (сверху < вы && шевеление[сверху] < порог) сверху += 1;
  let снизу = вы - 1;
  while (снизу > сверху && шевеление[снизу] < порог) снизу -= 1;

  /*  Полосу шире половины кадра не режем: скорее всего ошиблись, а
      не у ролика половина — интерфейс.                             */
  if (сверху > вы * 0.4 || вы - 1 - снизу > вы * 0.4) {
    return { рамка: начальная, нашли: Boolean(поля) };
  }

  /*  Строки считались внутри обрезанной картинки — переводим обратно
      в точки исходника.                                            */
  const кВысоте = начальная.h / вы;
  const сдвиг = Math.round((сверху * кВысоте) / 2) * 2;
  const низ = Math.round(((снизу + 1) * кВысоте) / 2) * 2;
  const y = начальная.y + сдвиг;
  const h = Math.max(2, низ - сдвиг);
  const нашли = Boolean(поля) || сдвиг > 0 || h < начальная.h;

  return {
    рамка: { x: начальная.x, y, w: начальная.w, h },
    нашли,
  };
}

/*  ЧИСТАЯ ОСНОВА. Обрезаем интерфейс, убираем шум записи экрана,
    поднимаем резкость и растягиваем до нужного размера. Длинная
    сторона кадра задаётся снаружи: вертикальный ролик идёт в
    1080×1920, горизонтальный — наоборот.                           */
export type РазмерОсновы = { ширина: number; высота: number };

export async function собратьОснову(
  вход: string,
  выход: string,
  рамка: Рамка,
  размер: РазмерОсновы,
): Promise<void> {
  /*  Никакого pad: размер уже посчитан по обрезанной картинке. Если
      дополнять до «правильного» 16:9, срезанные чёрные поля тут же
      вернутся обратно — именно это и случилось на первом же ролике. */
  const фильтры = [
    `crop=${рамка.w}:${рамка.h}:${рамка.x}:${рамка.y}`,
    "hqdn3d=3:3:6:6",
    `scale=${размер.ширина}:${размер.высота}:flags=lanczos`,
    "unsharp=5:5:1.0",
  ].join(",");

  const { код, вывод } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-y",
      "-i",
      вход,
      "-vf",
      фильтры,
      "-r",
      "30",
      "-c:v",
      "libx264",
      "-profile:v",
      "high",
      "-preset",
      "slow",
      "-crf",
      "14",
      "-pix_fmt",
      "yuv420p",
      "-movflags",
      "+faststart",
      "-c:a",
      "aac",
      "-b:a",
      "192k",
      выход,
    ],
    { срокМс: 110_000 },
  );
  if (код !== 0) {
    throw new Error(`Не удалось собрать основу: ${вывод.split("\n").slice(-3).join(" ").trim()}`);
  }
}

/*  КАДРЫ СНИМАЕТ FFMPEG, А НЕ БРАУЗЕР.

    Раньше раскадровка собиралась в браузере перемоткой `<video>`. На
    коротком mp4 это работало, а на настоящем ролике — нет: длинный
    .mov с частыми склейками отдавал один и тот же первый кадр на все
    времена. Браузеру незачем знать, как устроено видео, — пусть кадры
    достаёт тот же ffmpeg, что собирает основу.                      */

/** Один кадр в заданной точке. Точная перемотка: -ss перед -i. */
export async function снятьКадр(
  файл: string,
  время: number,
  выход: string,
  ширина: number,
): Promise<boolean> {
  const { код } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-y",
      /*  -ss до -i перематывает быстро, но по ключевым кадрам; добавляем
          -accurate_seek, иначе кадр уедет к ближайшей опорной точке.  */
      "-accurate_seek",
      "-ss",
      время.toFixed(3),
      "-i",
      файл,
      "-frames:v",
      "1",
      "-vf",
      `scale=${ширина}:-2:flags=lanczos`,
      "-q:v",
      "3",
      выход,
    ],
    { срокМс: 30_000 },
  );
  return код === 0;
}

/*  Пачка кадров одним проходом. Для раскадровки это куда быстрее, чем
    дёргать ffmpeg на каждый кадр: один проход по файлу вместо сотни. */
export async function снятьРяд(
  файл: string,
  шаг: number,
  папка: string,
  образец: string,
  ширина: number,
): Promise<number[]> {
  const { код, вывод, времена } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-y",
      "-i",
      файл,
      "-vf",
      /*  Отбираем кадры по времени, а не фильтром fps: тот берёт кадр
          из середины интервала и переставляет метку на начало — кадр
          с подписью «0,0 с» приходил из 0,2 с. select сохраняет и
          кадр, и его настоящее время, которое печатает showinfo.   */
      `select='isnan(prev_selected_t)+gte(t-prev_selected_t,${шаг})',scale=${ширина}:-2:flags=lanczos,showinfo`,
      "-fps_mode",
      "passthrough",
      "-q:v",
      "4",
      `${папка}/${образец}`,
    ],
    { срокМс: 180_000, времена: true },
  );
  if (код !== 0) {
    throw new Error(`Не удалось снять раскадровку: ${вывод.split("\n").slice(-2).join(" ")}`);
  }
  return времена;
}

/*  ГДЕ СКЛЕЙКИ. Встроенный признак смены сцены у ffmpeg: он сравнивает
    соседние кадры целиком и ведёт себя одинаково на любом материале —
    в отличие от прежнего разбора в браузере, который на настоящем
    ролике не нашёл ни одной склейки.                               */
export async function найтиСклейки(файл: string, порог = 0.3): Promise<number[]> {
  const { код, времена } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-i",
      файл,
      "-vf",
      `select='gt(scene,${порог})',showinfo`,
      "-f",
      "null",
      "-",
    ],
    { срокМс: 180_000, времена: true },
  );
  if (код !== 0) return [];
  const точки: number[] = [];
  for (const т of времена) {
    /*  Две склейки подряд в пределах трети секунды — одна склейка. */
    if (точки.length && т - точки[точки.length - 1] < 0.35) continue;
    точки.push(Number(т.toFixed(3)));
  }
  return точки;
}

/*  СКЛЕЙКИ ПО ЦВЕТУ.

    Встроенный признак смены сцены у ffmpeg смотрит в основном на
    яркость и пропускает склейку между двумя разными, но одинаково
    тёмными цветами. Поэтому считаем ещё и сами: берём десяток кадров
    в секунду маленькими, сравниваем по всем трём каналам и ищем
    всплески. Порог — от спокойной части ролика, иначе сами склейки
    задирают его выше себя.                                         */
const ШИРИНА_СКЛЕЕК = 128;
const ВЫБОРОК_В_СЕКУНДУ = 10;

export async function найтиСклейкиПоЦвету(
  файл: string,
  сведения: СведенияРолика,
): Promise<number[]> {
  if (!сведения.длительность) return [];
  const ши = ШИРИНА_СКЛЕЕК;
  const вы = Math.max(8, Math.round((сведения.высота * ши) / сведения.ширина / 2) * 2);
  const куски: Buffer[] = [];
  const { код } = await запуститьFfmpeg(
    [
      "-hide_banner",
      "-i",
      файл,
      "-vf",
      `fps=${ВЫБОРОК_В_СЕКУНДУ},scale=${ши}:${вы}:flags=bilinear,format=rgb24`,
      "-f",
      "rawvideo",
      "-",
    ],
    { срокМс: 180_000, наВыход: (к) => куски.push(к) },
  );
  if (код !== 0) return [];

  const всё = Buffer.concat(куски);
  const размер = ши * вы * 3;
  const кадров = Math.floor(всё.length / размер);
  if (кадров < 3) return [];

  const разницы: number[] = [];
  for (let к = 1; к < кадров; к += 1) {
    const было = к - 1;
    let сумма = 0;
    let n = 0;
    for (let p = 0; p < размер; p += 9) {
      сумма += Math.abs(всё[к * размер + p] - всё[было * размер + p]);
      сумма += Math.abs(всё[к * размер + p + 1] - всё[было * размер + p + 1]);
      сумма += Math.abs(всё[к * размер + p + 2] - всё[было * размер + p + 2]);
      n += 3;
    }
    разницы.push(сумма / n / 255);
  }

  const спокойные = [...разницы]
    .sort((a, b) => a - b)
    .slice(0, Math.max(2, Math.floor(разницы.length * 0.8)));
  const среднее = спокойные.reduce((a, b) => a + b, 0) / спокойные.length;
  const разброс = Math.sqrt(
    спокойные.reduce((a, x) => a + (x - среднее) ** 2, 0) / Math.max(1, спокойные.length - 1),
  );
  const порог = Math.max(0.06, среднее + 4 * разброс);

  const точки: number[] = [];
  for (let i = 0; i < разницы.length; i += 1) {
    if (разницы[i] <= порог) continue;
    /*  Берём только вершину всплеска: наплыв даёт несколько кадров
        подряд, а склейка там одна.                                 */
    if (i > 0 && разницы[i - 1] > разницы[i]) continue;
    if (i < разницы.length - 1 && разницы[i + 1] > разницы[i]) continue;
    const т = Number(((i + 1) / ВЫБОРОК_В_СЕКУНДУ).toFixed(2));
    if (точки.length && т - точки[точки.length - 1] < 0.35) continue;
    точки.push(т);
  }
  return точки;
}

/*  Общий ответ: что нашёл ffmpeg плюс что нашли мы сами.          */
export async function всеСклейки(
  файл: string,
  сведения: СведенияРолика,
): Promise<number[]> {
  const [свои, ffmpeg] = await Promise.all([
    найтиСклейкиПоЦвету(файл, сведения),
    найтиСклейки(файл, 0.2),
  ]);
  const вместе = [...свои, ...ffmpeg].sort((a, b) => a - b);
  const чисто: number[] = [];
  for (const т of вместе) {
    if (чисто.length && т - чисто[чисто.length - 1] < 0.35) continue;
    чисто.push(т);
  }
  return чисто;
}
