/*  РУССКИЕ ИМЕНА ВНУТРИ АРХИВА.

    JSZip помечает имена сразу двумя способами: ставит флаг «имя в
    UTF-8» и вдобавок кладёт отдельное поле Unicode Path (0x7075) с
    тем же именем. Эта пара сбивает часть распаковщиков: они читают
    дополнительное поле, не сходятся с ним контрольной суммой и
    выписывают имя escape-последовательностями — «#U0444» вместо «ф».

    Здесь мы проходим по готовому архиву и убираем дополнительные поля
    с именами, оставляя только флаг. Содержимое файлов не трогаем —
    правим лишь заголовки и смещения.                                */

const ЛОКАЛЬНЫЙ = 0x04034b50;
const ЦЕНТРАЛЬНЫЙ = 0x02014b50;
const КОНЕЦ = 0x06054b50;
/** Поля с именами, которые и сбивают распаковщики. */
const ЛИШНИЕ = new Set([0x7075, 0x6375]);

function убратьЛишние(доп: Uint8Array): Uint8Array {
  const куски: Uint8Array[] = [];
  let i = 0;
  while (i + 4 <= доп.length) {
    const id = доп[i] | (доп[i + 1] << 8);
    const размер = доп[i + 2] | (доп[i + 3] << 8);
    const конец = i + 4 + размер;
    if (конец > доп.length) break;
    if (!ЛИШНИЕ.has(id)) куски.push(доп.subarray(i, конец));
    i = конец;
  }
  const всего = куски.reduce((а, к) => а + к.length, 0);
  const итог = new Uint8Array(всего);
  let п = 0;
  for (const к of куски) {
    итог.set(к, п);
    п += к.length;
  }
  return итог;
}

type Запись = {
  /** Смещение локального заголовка в исходном архиве. */
  где: number;
  /** Смещение центральной записи в исходном архиве. */
  гдеЦентр: number;
  длинаЦентра: number;
};

/*  Если архив устроен непривычно — отдаём его как есть. Лучше прежние
    имена, чем сломанный файл.                                       */
export function починитьИмена(исходный: Uint8Array): Uint8Array {
  const dv = new DataView(исходный.buffer, исходный.byteOffset, исходный.byteLength);

  /*  Конец архива ищем с хвоста: за ним может быть комментарий.     */
  let конец = -1;
  for (let i = исходный.length - 22; i >= 0 && i > исходный.length - 70000; i -= 1) {
    if (dv.getUint32(i, true) === КОНЕЦ) {
      конец = i;
      break;
    }
  }
  if (конец < 0) return исходный;

  const записейВсего = dv.getUint16(конец + 10, true);
  const центрДлина = dv.getUint32(конец + 12, true);
  const центрНачало = dv.getUint32(конец + 16, true);
  if (центрНачало + центрДлина > исходный.length) return исходный;

  const записи: Запись[] = [];
  let п = центрНачало;
  for (let n = 0; n < записейВсего; n += 1) {
    if (dv.getUint32(п, true) !== ЦЕНТРАЛЬНЫЙ) return исходный;
    const флаг = dv.getUint16(п + 8, true);
    /*  Запись с описателем данных переносить сложнее, а JSZip их не
        делает — на всякий случай отступаем.                        */
    if (флаг & 0x8) return исходный;
    const имяДл = dv.getUint16(п + 28, true);
    const допДл = dv.getUint16(п + 30, true);
    const комДл = dv.getUint16(п + 32, true);
    const где = dv.getUint32(п + 42, true);
    const длина = 46 + имяДл + допДл + комДл;
    записи.push({ где, гдеЦентр: п, длинаЦентра: длина });
    п += длина;
  }
  if (!записи.length) return исходный;

  const поПорядку = [...записи].sort((а, б) => а.где - б.где);
  const куски: Uint8Array[] = [];
  const новыеСмещения = new Map<number, number>();
  let сдвиг = 0;

  for (let i = 0; i < поПорядку.length; i += 1) {
    const з = поПорядку[i];
    if (dv.getUint32(з.где, true) !== ЛОКАЛЬНЫЙ) return исходный;
    const имяДл = dv.getUint16(з.где + 26, true);
    const допДл = dv.getUint16(з.где + 28, true);
    const началоДанных = з.где + 30 + имяДл + допДл;
    const конецДанных = i + 1 < поПорядку.length ? поПорядку[i + 1].где : центрНачало;
    if (конецДанных < началоДанных) return исходный;

    const доп = убратьЛишние(исходный.subarray(з.где + 30 + имяДл, з.где + 30 + имяДл + допДл));
    const заголовок = new Uint8Array(30 + имяДл + доп.length);
    заголовок.set(исходный.subarray(з.где, з.где + 30 + имяДл), 0);
    new DataView(заголовок.buffer).setUint16(28, доп.length, true);
    заголовок.set(доп, 30 + имяДл);

    новыеСмещения.set(з.где, сдвиг);
    куски.push(заголовок, исходный.subarray(началоДанных, конецДанных));
    сдвиг += заголовок.length + (конецДанных - началоДанных);
  }

  const новыйЦентр = сдвиг;
  for (const з of записи) {
    const имяДл = dv.getUint16(з.гдеЦентр + 28, true);
    const допДл = dv.getUint16(з.гдеЦентр + 30, true);
    const комДл = dv.getUint16(з.гдеЦентр + 32, true);
    const доп = убратьЛишние(
      исходный.subarray(з.гдеЦентр + 46 + имяДл, з.гдеЦентр + 46 + имяДл + допДл),
    );
    const запись = new Uint8Array(46 + имяДл + доп.length + комДл);
    запись.set(исходный.subarray(з.гдеЦентр, з.гдеЦентр + 46 + имяДл), 0);
    const вид = new DataView(запись.buffer);
    вид.setUint16(30, доп.length, true);
    вид.setUint32(42, новыеСмещения.get(з.где) ?? 0, true);
    запись.set(доп, 46 + имяДл);
    запись.set(
      исходный.subarray(
        з.гдеЦентр + 46 + имяДл + допДл,
        з.гдеЦентр + 46 + имяДл + допДл + комДл,
      ),
      46 + имяДл + доп.length,
    );
    куски.push(запись);
    сдвиг += запись.length;
  }

  const хвост = исходный.subarray(конец).slice();
  const видХвоста = new DataView(хвост.buffer, хвост.byteOffset, хвост.byteLength);
  видХвоста.setUint32(12, сдвиг - новыйЦентр, true);
  видХвоста.setUint32(16, новыйЦентр, true);
  куски.push(хвост);

  const всего = куски.reduce((а, к) => а + к.length, 0);
  const итог = new Uint8Array(всего);
  let место = 0;
  for (const к of куски) {
    итог.set(к, место);
    место += к.length;
  }
  return итог;
}

/** То же самое, но для готового архива из JSZip. */
export async function архивСРусскимиИменами(архив: Blob): Promise<Blob> {
  try {
    const байты = new Uint8Array(await архив.arrayBuffer());
    const готово = починитьИмена(байты);
    return new Blob([готово as unknown as BlobPart], { type: "application/zip" });
  } catch {
    /*  Что-то пошло не так — отдаём исходный архив: имена там хуже,
        но файл точно целый.                                        */
    return архив;
  }
}
