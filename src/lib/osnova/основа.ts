import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import {
  найтиРамку,
  сведенияРолика,
  собратьОснову,
  type Рамка,
  type СведенияРолика,
} from "@/lib/osnova/ffmpeg";
import { папкаРазбора } from "@/lib/osnova/папка";

/*  ЧИСТАЯ ВИДЕО-ОСНОВА.

    Трендовый ролик почти всегда приходит записью экрана: сверху шапка
    Instagram, снизу подписи и кнопки. Seedance возьмёт такой ролик как
    основу вместе с интерфейсом и честно нарисует его в результате.
    Поэтому интерфейс срезаем, запись чистим от шума и пересобираем в
    приличном размере.                                                */

/** Ниже этой ширины после обрезки толку от исходника мало. */
export const МЕЛКИЙ_ИСХОДНИК = 540;

export type РазборОсновы = {
  id: string;
  имя: string;
  исходник: СведенияРолика;
  рамка: Рамка;
  /** Рамку нашли сами или она осталась во весь кадр. */
  нашлиРамку: boolean;
  /** Размер картинки после обрезки — по нему судим о мелком исходнике. */
  послеОбрезки: { ширина: number; высота: number };
  большая: { файл: string; ширина: number; высота: number; байт: number };
  запасная: { файл: string; ширина: number; высота: number; байт: number };
  вертикальный: boolean;
};

const ФАЙЛ_РАЗБОРА = "разбор.json";

/*  Размер основы. Вертикальный ролик идёт в 1080×1920, горизонтальный
    и квадратный — в ту же площадь, но по своему соотношению: формат
    берётся из ролика, а не навязывается.                            */
function размерыОсновы(ширина: number, высота: number) {
  const вертикальный = высота >= ширина;
  if (вертикальный) {
    return {
      вертикальный,
      большая: { ширина: 1080, высота: 1920 },
      запасная: { ширина: 720, высота: 1280 },
    };
  }
  return {
    вертикальный,
    большая: { ширина: 1920, высота: 1080 },
    запасная: { ширина: 1280, высота: 720 },
  };
}

export async function сохранитьРазбор(id: string, разбор: РазборОсновы): Promise<void> {
  const папка = await папкаРазбора(id);
  await writeFile(path.join(папка, ФАЙЛ_РАЗБОРА), JSON.stringify(разбор, null, 2), "utf8");
}

export async function читатьРазбор(id: string): Promise<РазборОсновы | null> {
  try {
    const папка = await папкаРазбора(id);
    const текст = await readFile(path.join(папка, ФАЙЛ_РАЗБОРА), "utf8");
    return JSON.parse(текст) as РазборОсновы;
  } catch {
    return null;
  }
}

/*  Собрать обе основы по готовой рамке. Вынесено отдельно: когда
    владелец поправит рамку руками, пересобирать надо только это.    */
export async function пересобрать(
  id: string,
  исходный: string,
  имя: string,
  сведения: СведенияРолика,
  рамка: Рамка,
  нашлиРамку: boolean,
): Promise<РазборОсновы> {
  const папка = await папкаРазбора(id);
  const { вертикальный, большая, запасная } = размерыОсновы(рамка.w, рамка.h);

  const имяБольшой = `основа-${большая.ширина}x${большая.высота}.mp4`;
  const имяЗапасной = `основа-${запасная.ширина}x${запасная.высота}.mp4`;

  await собратьОснову(исходный, path.join(папка, имяБольшой), рамка, большая);
  await собратьОснову(исходный, path.join(папка, имяЗапасной), рамка, запасная);

  const вес = async (файл: string) => (await readFile(path.join(папка, файл))).byteLength;

  const разбор: РазборОсновы = {
    id,
    имя,
    исходник: сведения,
    рамка,
    нашлиРамку,
    послеОбрезки: { ширина: рамка.w, высота: рамка.h },
    большая: { файл: имяБольшой, ...большая, байт: await вес(имяБольшой) },
    запасная: { файл: имяЗапасной, ...запасная, байт: await вес(имяЗапасной) },
    вертикальный,
  };
  await сохранитьРазбор(id, разбор);
  return разбор;
}

/*  Полный проход по свежему ролику: что за файл, где интерфейс, и две
    основы.                                                          */
export async function разобратьРолик(
  id: string,
  исходный: string,
  имя: string,
): Promise<РазборОсновы> {
  const сведения = await сведенияРолика(исходный);
  const { рамка, нашли } = await найтиРамку(исходный, сведения);
  return пересобрать(id, исходный, имя, сведения, рамка, нашли);
}

/*  Что показать человеку галочками: что сделано, а где надо быть
    осторожнее.                                                      */
export type Проверка = { вид: "ok" | "warn"; текст: string };

export function проверки(разбор: РазборОсновы): Проверка[] {
  const список: Проверка[] = [];
  const { исходник, послеОбрезки } = разбор;

  список.push(
    разбор.нашлиРамку
      ? { вид: "ok", текст: "Интерфейс и подписи обрезаны" }
      : {
          вид: "ok",
          текст: "Неподвижных полос не нашлось — кадр взят целиком",
        },
  );
  список.push({
    вид: "ok",
    текст: `Шум убран, резкость, ${разбор.большая.ширина}×${разбор.большая.высота}, 30 к/с, высокий битрейт`,
  });

  const соотношение = разбор.вертикальный ? "вертикаль 9:16" : "горизонталь";
  список.push({
    вид: "ok",
    текст: `${соотношение} · ${исходник.длительность.toFixed(1)} сек`,
  });

  if (послеОбрезки.ширина < МЕЛКИЙ_ИСХОДНИК) {
    список.push({
      вид: "warn",
      текст: `Исходник мелкий (${послеОбрезки.ширина}×${послеОбрезки.высота} после обрезки) — возьмите исходный файл ролика, а не запись экрана. Если Seedance не примет большую основу, попробуйте запасную.`,
    });
  }

  return список;
}
