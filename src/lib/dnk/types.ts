/*  ДНК РОЛИКА — ролик в разобранном виде.

    Промпт описывает ролик словами и каждый раз даёт «что-то похожее».
    ДНК описывает его по частям: где кончается одна сцена и начинается
    другая, чем они склеены, что в сцене держать неизменным и что можно
    подменить. По такой записи каждую сцену потом генерируют отдельно и
    собирают обратно теми же переходами.                               */

/** Чем склеены две соседние сцены. */
export type ВидПерехода =
  | "склейка"
  | "вспышка"
  | "взмах камеры"
  | "затемнение"
  | "наплыв";

export const ВИДЫ_ПЕРЕХОДА: ВидПерехода[] = [
  "склейка",
  "вспышка",
  "взмах камеры",
  "затемнение",
  "наплыв",
];

/*  Значок перехода на дорожке монтажа — как в образце.                */
export const ЗНАЧКИ_ПЕРЕХОДА: Record<ВидПерехода, string> = {
  "склейка": "✂",
  "вспышка": "✦",
  "взмах камеры": "↯",
  "затемнение": "◐",
  "наплыв": "◇",
};

export type Переход = {
  вид: ВидПерехода;
  /** Время стыка, сек. */
  время: number;
  /** Сколько длится сам переход, сек (у резкой склейки — 0). */
  длительность: number;
  /*  Признаки сошлись слабо — показываем «проверьте» и ждём, что
      владелец поправит вид перехода руками.                         */
  проверьте: boolean;
  /** Поставлен владельцем вручную — больше не пересчитываем. */
  вручную?: boolean;
};

/*  Крупность плана. Пусто — измерить не вышло, выберет человек:
    в карточке «Для Seedance» это выпадающий список.               */
export type Крупность = "крупный" | "макро" | "средний" | "общий" | "";
export const КРУПНОСТИ: Крупность[] = ["крупный", "макро", "средний", "общий"];

/*  ГЕНЫ СЦЕНЫ. Заморожённое держит сюжет и форму, открытое можно
    подменить при генерации.                                          */
export type ГеныСцены = {
  /** 🔒 что происходит — пишет владелец, одной фразой */
  действие: string;
  /*  То же по-английски. Необязательно: если пусто, в английский
      текст для Seedance уходит русская фраза — лучше так, чем
      пустое место.                                               */
  действиеEn: string;
  /** 🔒 крупность плана — грубая прикидка по измерениям */
  план: Крупность;
  /** 🔒 движение камеры в этой сцене — из измерений */
  камера: string;
  /** 🔒 длительность считается из границ, здесь не хранится */
  /** ✎ свет и цвет — из палитры и яркости */
  свет: string;
  /** ✎ кто в кадре — руками */
  герой: string;
  /** ✎ где — руками */
  место: string;
  /** ✎ что рекламируется — руками */
  товар: string;
};

export type СлотСцены = "товар" | "место" | "герой";
export const СЛОТЫ_СЦЕНЫ: СлотСцены[] = ["товар", "место", "герой"];

export type СценаДНК = {
  id: string;
  /** Границы сцены в секундах. */
  начало: number;
  конец: number;
  /** Кадр из середины — для подписи и предпросмотра. */
  середина: number;
  /** Название сцены — своё или «Сцена 3». */
  имя: string;
  /** Цвет полоски в нити ДНК. */
  цвет: string;
  /** Какие метки шаблона прикладываются к этой сцене. */
  слоты: СлотСцены[];
  /*  Сцену уже сгенерировали в Seedance — галочка в нити и в плане
      монтажа, чтобы не потерять место в длинном ролике.           */
  сгенерирована?: boolean;
  гены: ГеныСцены;
  /*  Измерения по этой сцене: по ним заполняются гены и по ним же
      видно, насколько им можно верить.                             */
  замеры: {
    яркость: number;
    насыщенность: number;
    теплота: number;
    движение: number;
    детализация: number;
    палитра: string[];
  };
};

/*  КЛЮЧЕВЫЕ КАДРЫ: первый и последний кадр каждой сцены в полном
    разрешении ролика плюс один средний. Живут отдельно от самой ДНК —
    это файлы, а не описание.                                        */
export type КадрыСцены = {
  sceneId: string;
  первый: { время: number; url: string; blob: Blob } | null;
  средний: { время: number; url: string; blob: Blob } | null;
  последний: { время: number; url: string; blob: Blob } | null;
};

export type ДНК = {
  версия: "1.0";
  источник: string;
  длительность: number;
  ширина: number;
  высота: number;
  fps: number;
  сцены: СценаДНК[];
  переходы: Переход[];
  /** Когда разобрали. */
  когда: string;
};

/*  То, что уходит в историю и в файл: ДНК без тяжёлых картинок.      */
export type ДНКдляИстории = {
  версия: string;
  источник: string;
  длительность: number;
  сцен: number;
  сцены: Array<{
    n: number;
    from: number;
    to: number;
    имя: string;
    slots: СлотСцены[];
    locked: {
      действие: string;
      действиеEn: string;
      план: string;
      камера: string;
      ритм: number;
    };
    open: { свет: string; герой: string; место: string; товар: string };
    сгенерирована: boolean;
    first: string;
    last: string;
    transition_out: ВидПерехода | null;
  }>;
};

