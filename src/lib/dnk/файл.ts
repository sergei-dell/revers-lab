import { файлSeedance, type РежимКадров } from "@/lib/dnk/seedance";
import type {
  ДНК,
  ДНКдляИстории,
  КадрыСцены,
  Переход,
  СценаДНК,
} from "@/lib/dnk/types";

/*  ФАЙЛ ДНК. Одна папка-архив, в которой лежит всё, что нужно, чтобы
    собрать ролик заново: описание сцен в `dnk.json` и по два-три кадра
    на сцену. Версия формата — 1.0.                                   */

function переходПосле(переходы: Переход[], i: number): Переход | null {
  return переходы[i] ?? null;
}

/** Описание ДНК без картинок — оно же уходит в историю разборов. */
export function описаниеДНК(днк: ДНК): ДНКдляИстории {
  return {
    версия: днк.версия,
    источник: днк.источник,
    длительность: Number(днк.длительность.toFixed(3)),
    сцен: днк.сцены.length,
    сцены: днк.сцены.map((с, i) => {
      const переход = переходПосле(днк.переходы, i);
      return {
        n: i + 1,
        from: Number(с.начало.toFixed(3)),
        to: Number(с.конец.toFixed(3)),
        имя: с.имя,
        slots: с.слоты,
        locked: {
          действие: с.гены.действие,
          действиеEn: с.гены.действиеEn,
          план: с.гены.план,
          камера: с.гены.камера,
          ритм: Number((с.конец - с.начало).toFixed(3)),
        },
        open: {
          свет: с.гены.свет,
          герой: с.гены.герой,
          место: с.гены.место,
          товар: с.гены.товар,
        },
        сгенерирована: Boolean(с.сгенерирована),
        first: `s${i + 1}_first.jpg`,
        last: `s${i + 1}_last.jpg`,
        transition_out: переход ? переход.вид : null,
      };
    }),
  };
}

/*  Полный `dnk.json`: то же описание плюс замеры и точные параметры
    переходов. Его читает будущая генерация.                          */
export function файлДНК(днк: ДНК): Record<string, unknown> {
  return {
    dnk: днк.версия,
    source: днк.источник,
    duration: Number(днк.длительность.toFixed(3)),
    width: днк.ширина,
    height: днк.высота,
    fps: Number(днк.fps.toFixed(2)),
    created: днк.когда,
    scenes: днк.сцены.map((с, i) => {
      const переход = переходПосле(днк.переходы, i);
      return {
        n: i + 1,
        id: с.id,
        name: с.имя,
        from: Number(с.начало.toFixed(3)),
        to: Number(с.конец.toFixed(3)),
        slots: с.слоты,
        locked: {
          action: с.гены.действие,
          action_en: с.гены.действиеEn,
          shot: с.гены.план,
          camera: с.гены.камера,
          rhythm: Number((с.конец - с.начало).toFixed(3)),
        },
        generated: Boolean(с.сгенерирована),
        replace: {
          light: с.гены.свет,
          hero: с.гены.герой,
          place: с.гены.место,
          product: с.гены.товар,
        },
        measured: с.замеры,
        first: `s${i + 1}_first.jpg`,
        mid: `s${i + 1}_mid.jpg`,
        last: `s${i + 1}_last.jpg`,
        motion: `source.mp4#t=${с.начало.toFixed(3)},${с.конец.toFixed(3)}`,
        transition_out: переход
          ? { kind: переход.вид, seconds: переход.длительность, check: переход.проверьте }
          : null,
      };
    }),
  };
}

/*  Архив: описание и кадры. Имена кадров те же, что в `dnk.json`,
    чтобы сборщику не приходилось угадывать.                          */
export async function архивДНК(
  днк: ДНК,
  кадры: Map<string, КадрыСцены>,
  режим: РежимКадров = "кадры",
): Promise<Blob> {
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  zip.file("dnk.json", JSON.stringify(файлДНК(днк), null, 2));
  /*  Памятка для ручной генерации: порядок картинок, тексты и план
      монтажа. С ней архив самодостаточен — сайт открывать не нужно. */
  zip.file("seedance.txt", файлSeedance(днк, режим));

  днк.сцены.forEach((с, i) => {
    const набор = кадры.get(с.id);
    if (!набор) return;
    if (набор.первый) zip.file(`s${i + 1}_first.jpg`, набор.первый.blob);
    if (набор.средний) zip.file(`s${i + 1}_mid.jpg`, набор.средний.blob);
    if (набор.последний) zip.file(`s${i + 1}_last.jpg`, набор.последний.blob);
  });

  /*  Короткая расшифровка рядом с файлом: архив могут открыть через
      полгода, и тогда «s3_last.jpg» ничего не скажет.               */
  const список = днк.сцены
    .map((с, i) => {
      const переход = переходПосле(днк.переходы, i);
      return [
        `${i + 1}\t${с.имя}`,
        `${с.начало.toFixed(3)}–${с.конец.toFixed(3)} сек`,
        `${(с.конец - с.начало).toFixed(2)} сек`,
        с.слоты.length ? с.слоты.map((х) => `[${х}]`).join(" ") : "—",
        переход ? переход.вид : "конец ролика",
      ].join("\t");
    })
    .join("\n");
  zip.file(
    "сцены.tsv",
    `номер\tимя\tграницы\tдлительность\tметки\tпереход на выходе\n${список}\n`,
  );

  return zip.generateAsync({ type: "blob" });
}

export function имяАрхива(источник: string): string {
  const основа = источник.replace(/\.[^.]+$/, "").slice(0, 48) || "клип";
  return `${основа}-днк.zip`;
}
