import { CAMERA_LABELS } from "@/lib/video/analyze";
import type { Analysis, CameraMove } from "@/lib/types";
import type { СыраяСцена, ЗамерКадра } from "@/lib/dnk/нарезка";
import {
  ЦВЕТА_СЦЕН,
  пустыеГены,
  type Крупность,
  type СценаДНК,
} from "@/lib/dnk/types";

/*  ГЕНЫ СЦЕНЫ — то, что о сцене известно без нейросети.

    Заполняем только измеренное: длительность, движение камеры, свет и
    цвет, грубую крупность плана. Действие, герой, место и товар
    остаются пустыми — их вписывает владелец, а потом за него это
    сделает модель. Чтобы подключить её, достаточно заменить одну
    функцию `заполнитьМоделью`, экран переписывать не придётся.       */

function среднее(значения: number[]): number {
  return значения.length ? значения.reduce((a, b) => a + b, 0) / значения.length : 0;
}

function медиана(значения: number[]): number {
  if (!значения.length) return 0;
  const ряд = [...значения].sort((a, b) => a - b);
  const середина = Math.floor(ряд.length / 2);
  return ряд.length % 2 ? ряд[середина] : (ряд[середина - 1] + ряд[середина]) / 2;
}

/*  ДВИЖЕНИЕ КАМЕРЫ ВНУТРИ СЦЕНЫ. Общий разбор считает движение на весь
    ролик; здесь те же правила, но по кадрам одной сцены.             */
function камераСцены(замеры: ЗамерКадра[]): CameraMove {
  const разницы = замеры.slice(1).map((з) => з.разница);
  if (!разницы.length) return "static";
  const dxs = замеры.slice(1).map((з) => з.dx);
  const dys = замеры.slice(1).map((з) => з.dy);
  const medDx = медиана(dxs);
  const medDy = медиана(dys);
  const движение = среднее(разницы);
  const пик = Math.max(...разницы);
  const покой = разницы.filter((d) => d < 0.018).length / разницы.length;

  /*  Сперва проверяем покой. Иначе на почти неподвижной картинке
      поиск сдвига цепляется за шум и выдаёт уверенный «тилт вниз»
      там, где камера не двигалась вовсе.                         */
  if (покой > 0.8 || движение < 0.012) return "static";
  if (пик > 0.16 && Math.abs(medDx) >= 3) return "whip";
  if (Math.abs(medDx) > 1.2 && Math.abs(medDx) > Math.abs(medDy)) {
    return medDx > 0 ? "pan-left" : "pan-right";
  }
  if (Math.abs(medDy) > 1.1) return medDy > 0 ? "tilt-up" : "tilt-down";
  return "handheld";
}

/*  КРУПНОСТЬ ПЛАНА — грубо, по тому, как картинка отзывается на
    движение. На крупном плане небольшое смещение камеры перетряхивает
    весь кадр; на общем — почти ничего не меняется. Признак слабый,
    поэтому при сомнении оставляем пусто: лучше пустое поле, чем
    уверенная неправда.                                              */
function планСцены(замеры: ЗамерКадра[]): Крупность {
  const разницы = замеры.slice(1).map((з) => з.разница);
  if (разницы.length < 3) return "";
  const ход = медиана(замеры.slice(1).map((з) => Math.hypot(з.dx, з.dy)));
  const движение = среднее(разницы);
  const детализация = среднее(замеры.map((з) => з.детализация));
  if (ход < 0.5) return "";
  const отклик = движение / Math.max(0.25, ход);
  if (отклик > 0.055 && детализация < 0.3) return "крупный";
  if (отклик < 0.018) return "общий";
  if (отклик >= 0.018 && отклик <= 0.055) return "средний";
  return "";
}

/*  СВЕТ И ЦВЕТ СЦЕНЫ — человеческими словами из яркости, теплоты и
    насыщенности.                                                    */
function светСцены(замеры: ЗамерКадра[], палитра: string[]): string {
  if (!замеры.length) return "";
  const яркость = среднее(замеры.map((з) => з.яркость));
  const теплота = среднее(замеры.map((з) => з.теплота));
  const насыщенность = среднее(замеры.map((з) => з.насыщенность));

  const тон =
    яркость < 0.26 ? "тёмный кадр" : яркость > 0.62 ? "светлый кадр" : "средняя яркость";
  const температура =
    теплота > 0.045 ? "тёплый свет" : теплота < -0.045 ? "холодный свет" : "нейтральный свет";
  const сочность =
    насыщенность > 0.42 ? "сочный цвет" : насыщенность < 0.16 ? "почти обесцвечено" : "";

  const части = [тон, температура, сочность].filter(Boolean);
  if (палитра.length) части.push(палитра.slice(0, 3).join(" · "));
  return части.join(", ");
}

/*  Палитра сцены: берём цвета общего разбора и оставляем те, что ближе
    к средним цветам этой сцены. Точного разбора по сценам пока нет,
    но так подпись честнее, чем палитра всего ролика.                */
function палитраСцены(замеры: ЗамерКадра[], разбор: Analysis | null): string[] {
  if (!разбор?.palette?.length) return [];
  if (!замеры.length) return разбор.palette.slice(0, 3).map((ц) => ц.hex);
  const яркость = среднее(замеры.map((з) => з.яркость)) * 255;
  const теплота = среднее(замеры.map((з) => з.теплота)) * 255;
  return [...разбор.palette]
    .map((ц) => {
      const l = 0.2126 * ц.rgb[0] + 0.7152 * ц.rgb[1] + 0.0722 * ц.rgb[2];
      const t = ц.rgb[0] - ц.rgb[2];
      return { ц, далеко: Math.abs(l - яркость) + Math.abs(t - теплота) * 0.6 };
    })
    .sort((a, b) => a.далеко - b.далеко)
    .slice(0, 3)
    .map((x) => x.ц.hex);
}

export function собратьСцены(
  сырые: СыраяСцена[],
  разбор: Analysis | null,
): СценаДНК[] {
  return сырые.map((с, i) => {
    const палитра = палитраСцены(с.замеры, разбор);
    const камера = камераСцены(с.замеры);
    const гены = пустыеГены();
    гены.камера = CAMERA_LABELS[камера]?.ru ?? "";
    гены.план = планСцены(с.замеры);
    гены.свет = светСцены(с.замеры, палитра);
    return {
      id: `sc-${i + 1}-${Math.round(с.начало * 1000)}`,
      начало: с.начало,
      конец: с.конец,
      середина: Number(((с.начало + с.конец) / 2).toFixed(3)),
      имя: `Сцена ${i + 1}`,
      цвет: ЦВЕТА_СЦЕН[i % ЦВЕТА_СЦЕН.length],
      слоты: [],
      гены,
      замеры: {
        яркость: Number(среднее(с.замеры.map((з) => з.яркость)).toFixed(4)),
        насыщенность: Number(среднее(с.замеры.map((з) => з.насыщенность)).toFixed(4)),
        теплота: Number(среднее(с.замеры.map((з) => з.теплота)).toFixed(4)),
        движение: Number(среднее(с.замеры.slice(1).map((з) => з.разница)).toFixed(4)),
        детализация: Number(среднее(с.замеры.map((з) => з.детализация)).toFixed(4)),
        палитра,
      },
    };
  });
}

/*  МЕСТО ПОД МОДЕЛЬ. Сейчас возвращает «не подключено»; когда появится
    доступ к генерации, здесь будет запрос к ней, а экран останется
    прежним — он вызывает только эту функцию.                        */
export type ОтветМодели =
  | { готово: true; гены: Partial<СценаДНК["гены"]> }
  | { готово: false; почему: string };

export async function заполнитьМоделью(): Promise<ОтветМодели> {
  return { готово: false, почему: "Нужен доступ к модели" };
}

/*  Пересобрать номера и цвета после правок руками: сцены могли
    объединить, разрезать или сдвинуть границу.                      */
export function перенумеровать(сцены: СценаДНК[]): СценаДНК[] {
  return сцены.map((с, i) => ({
    ...с,
    цвет: ЦВЕТА_СЦЕН[i % ЦВЕТА_СЦЕН.length],
    имя: /^Сцена \d+$/.test(с.имя) ? `Сцена ${i + 1}` : с.имя,
    середина: Number(((с.начало + с.конец) / 2).toFixed(3)),
  }));
}
