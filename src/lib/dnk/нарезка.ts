import { seekVideo, makeCanvas, drawVideo } from "@/lib/video/capture";
import type { Переход, ВидПерехода } from "@/lib/dnk/types";

/*  ТОЧНАЯ НАРЕЗКА НА СЦЕНЫ.

    Обычный разбор берёт 28 выборок на весь ролик — этого хватает, чтобы
    описать ролик словами, но мало, чтобы найти склейки: между двумя
    выборками умещается целая сцена. Здесь выборка частая (ориентир — 10
    кадров в секунду), а найденный стык потом уточняется до кадра.

    Всё считается по пикселям в браузере, без нейросети.               */

/** Сколько выборок в секунду на черновом проходе. */
const ВЫБОРОК_В_СЕКУНДУ = 10;
/** Ширина картинки для измерений: больше не нужно, считать быстрее. */
const ШИРИНА = 128;
/** Сцены короче этого — не сцены, а мерцание на стыке. */
export const САМАЯ_КОРОТКАЯ_СЦЕНА = 0.3;
/** Дальше этого предела частый проход не идёт: ролики до минуты. */
export const ПРЕДЕЛ_ДЛИТЕЛЬНОСТИ = 60;

export type ЗамерКадра = {
  t: number;
  яркость: number;
  контраст: number;
  насыщенность: number;
  теплота: number;
  детализация: number;
  разница: number;
  dx: number;
  dy: number;
};

export type СыраяСцена = {
  начало: number;
  конец: number;
  замеры: ЗамерКадра[];
};

export type ИтогНарезки = {
  сцены: СыраяСцена[];
  переходы: Переход[];
  порог: number;
  выборок: number;
};

type Ход = (доля: number, подпись: string) => void;

function вСерый(data: Uint8ClampedArray, px: number): Float32Array {
  const gray = new Float32Array(px);
  for (let i = 0, p = 0; i < px; i += 1, p += 4) {
    gray[i] = 0.2126 * data[p] + 0.7152 * data[p + 1] + 0.0722 * data[p + 2];
  }
  return gray;
}

/*  Детализация по Собелю: у смазанного кадра она проваливается, и это
    главный признак взмаха камеры.                                    */
function резкость(gray: Float32Array, w: number, h: number): number {
  let sum = 0;
  let n = 0;
  for (let y = 1; y < h - 1; y += 2) {
    for (let x = 1; x < w - 1; x += 2) {
      const i = y * w + x;
      const gx =
        -gray[i - w - 1] - 2 * gray[i - 1] - gray[i + w - 1] +
        gray[i - w + 1] + 2 * gray[i + 1] + gray[i + w + 1];
      const gy =
        -gray[i - w - 1] - 2 * gray[i - w] - gray[i - w + 1] +
        gray[i + w - 1] + 2 * gray[i + w] + gray[i + w + 1];
      sum += Math.hypot(gx, gy);
      n += 1;
    }
  }
  return n ? sum / n / 255 : 0;
}

/*  Куда уехала картинка между соседними кадрами: грубый поиск сдвига.
    По нему видно проводку камеры.                                    */
function сдвиг(
  было: Float32Array,
  стало: Float32Array,
  w: number,
  h: number,
): { dx: number; dy: number } {
  const предел = 6;
  let лучший = Infinity;
  let bdx = 0;
  let bdy = 0;
  for (let dy = -предел; dy <= предел; dy += 2) {
    for (let dx = -предел; dx <= предел; dx += 2) {
      let acc = 0;
      let n = 0;
      for (let y = предел; y < h - предел; y += 3) {
        const sy = y + dy;
        for (let x = предел; x < w - предел; x += 3) {
          acc += Math.abs(было[y * w + x] - стало[sy * w + (x + dx)]);
          n += 1;
        }
      }
      const среднее = n ? acc / n : Infinity;
      if (среднее < лучший) {
        лучший = среднее;
        bdx = dx;
        bdy = dy;
      }
    }
  }
  return { dx: bdx, dy: bdy };
}

function среднее(значения: number[]): number {
  return значения.length ? значения.reduce((a, b) => a + b, 0) / значения.length : 0;
}

function разброс(значения: number[]): number {
  if (значения.length < 2) return 0;
  const m = среднее(значения);
  return Math.sqrt(значения.reduce((a, x) => a + (x - m) ** 2, 0) / (значения.length - 1));
}

/*  Один замер в заданной точке ролика. Возвращает и серую картинку:
    она нужна, чтобы сравнить со следующей.                           */
type Снимок = { gray: Float32Array; пиксели: Uint8ClampedArray };

async function замерить(
  video: HTMLVideoElement,
  t: number,
  canvas: HTMLCanvasElement,
  w: number,
  h: number,
  прежний: Снимок | null,
): Promise<{ замер: ЗамерКадра; снимок: Снимок }> {
  await seekVideo(video, t);
  const ctx = drawVideo(video, canvas);
  let картинка: ImageData;
  try {
    картинка = ctx.getImageData(0, 0, w, h);
  } catch {
    throw new Error(
      "Не удалось прочитать пиксели видео — источник защищён от кросс-доменного доступа.",
    );
  }
  const data = картинка.data;
  const px = w * h;
  const gray = вСерый(data, px);

  let сумЯркости = 0;
  let сумКвадратов = 0;
  let сумНасыщенности = 0;
  let сумТеплоты = 0;
  for (let i = 0, p = 0; i < px; i += 1, p += 4) {
    const r = data[p];
    const g = data[p + 1];
    const b = data[p + 2];
    const l = gray[i];
    сумЯркости += l;
    сумКвадратов += l * l;
    сумТеплоты += r - b;
    const макс = Math.max(r, g, b);
    const мин = Math.min(r, g, b);
    сумНасыщенности += макс === 0 ? 0 : (макс - мин) / макс;
  }

  let разница = 0;
  let dx = 0;
  let dy = 0;
  if (прежний) {
    /*  Считаем по всем трём каналам. По одной яркости склейка
        «синий → красный» почти не видна: цвета разные, а серого в
        них поровну — и склейка проскакивала незамеченной.        */
    const было = прежний.пиксели;
    let acc = 0;
    let n = 0;
    for (let i = 0, p = 0; i < px; i += 2, p += 8) {
      acc +=
        Math.abs(data[p] - было[p]) +
        Math.abs(data[p + 1] - было[p + 1]) +
        Math.abs(data[p + 2] - было[p + 2]);
      n += 1;
    }
    разница = n ? acc / n / 3 / 255 : 0;
    const ход = сдвиг(прежний.gray, gray, w, h);
    dx = ход.dx;
    dy = ход.dy;
  }

  return {
    снимок: { gray, пиксели: new Uint8ClampedArray(data) },
    замер: {
      t,
      яркость: сумЯркости / px / 255,
      контраст: Math.sqrt(Math.max(0, сумКвадратов / px - (сумЯркости / px) ** 2)) / 255,
      насыщенность: сумНасыщенности / px,
      теплота: сумТеплоты / px / 255,
      детализация: резкость(gray, w, h),
      разница,
      dx,
      dy,
    },
  };
}

/*  ЧТО ЗА ПЕРЕХОД. Смотрим узкое окно кадров вокруг стыка и решаем по
    признакам — без нейросети. Если признаки не сошлись, честно ставим
    «склейка» с пометкой «проверьте».                                 */
function определитьПереход(
  окно: ЗамерКадра[],
  стык: number,
  фоноваяДетализация: number,
): { вид: ВидПерехода; длительность: number; проверьте: boolean } {
  if (окно.length < 3) return { вид: "склейка", длительность: 0, проверьте: true };

  const яркости = окно.map((з) => з.яркость);
  const разницы = окно.slice(1).map((з) => з.разница);
  const пик = Math.max(...разницы, 0);
  const срЯркость = среднее(яркости);

  /*  ВСПЫШКА: яркость подскакивает вверх на 1–4 кадра и возвращается. */
  const граница = Math.max(0.16, срЯркость + 0.18);
  let вспышек = 0;
  let первая = -1;
  for (let i = 0; i < окно.length; i += 1) {
    if (окно[i].яркость > граница) {
      вспышек += 1;
      if (первая < 0) первая = i;
    }
  }
  if (вспышек >= 1 && вспышек <= 4 && первая > 0 && первая < окно.length - 1) {
    const до = окно[первая - 1].яркость;
    const после = окно[Math.min(окно.length - 1, первая + вспышек)].яркость;
    const скачок = окно[первая].яркость - Math.max(до, после);
    if (скачок > 0.14) {
      const длина = окно[Math.min(окно.length - 1, первая + вспышек)].t - окно[первая].t;
      return { вид: "вспышка", длительность: Number(длина.toFixed(3)), проверьте: false };
    }
  }

  /*  ЗАТЕМНЕНИЕ: картинка уходит почти в чёрное и возвращается.      */
  const минЯркость = Math.min(...яркости);
  if (минЯркость < 0.07 && срЯркость > 0.14) {
    const тёмные = окно.filter((з) => з.яркость < 0.1);
    const длина = тёмные.length > 1 ? тёмные[тёмные.length - 1].t - тёмные[0].t : 0.2;
    if (длина >= 0.08 && длина <= 1.2) {
      return { вид: "затемнение", длительность: Number(Math.max(0.2, длина).toFixed(3)), проверьте: false };
    }
  }

  /*  ВЗМАХ КАМЕРЫ: несколько кадров подряд смазаны и уехали в одну
      сторону. Одного смазанного кадра мало: у резкой склейки между
      двумя ровными заливками детализация тоже низкая, и признак
      срабатывал впустую. Поэтому нужен и заметный фоновый рисунок в
      кадре, и смаз минимум на двух кадрах, и ход в одну сторону.   */
  const рядом = окно.filter((з) => Math.abs(з.t - стык) < 0.14);
  const смазанных = рядом.filter(
    (з) => фоноваяДетализация > 0 && з.детализация < фоноваяДетализация * 0.72,
  ).length;
  const ходы = рядом.map((з) => з.dx);
  const вОднуСторону =
    ходы.filter((d) => d >= 4).length >= 2 || ходы.filter((d) => d <= -4).length >= 2;
  if (фоноваяДетализация > 0.02 && смазанных >= 2 && вОднуСторону) {
    return { вид: "взмах камеры", длительность: 0.12, проверьте: false };
  }

  /*  НАПЛЫВ: смена размазана по времени — нет одного резкого скачка,
      зато несколько кадров подряд заметно отличаются от соседей.     */
  const заметные = окно.slice(1).filter((з) => з.разница > пик * 0.45 && з.разница > 0.045);
  if (заметные.length >= 3 && пик < 0.3) {
    const длина = заметные[заметные.length - 1].t - заметные[0].t;
    if (длина >= 0.18 && длина <= 1.05) {
      return { вид: "наплыв", длительность: Number(длина.toFixed(3)), проверьте: false };
    }
  }

  /*  РЕЗКАЯ СКЛЕЙКА: один кадр ни на что не похож. Если скачок слабый,
      просим посмотреть глазами.                                      */
  return { вид: "склейка", длительность: 0, проверьте: пик < 0.17 };
}

/*  Разрез ролика на сцены. Два прохода: частый черновой по всему ролику
    и покадровое уточнение около каждого найденного стыка.            */
export async function разрезатьНаСцены(
  video: HTMLVideoElement,
  параметры: {
    длительность: number;
    fps: number;
    onProgress?: Ход;
    отменено?: () => boolean;
  },
): Promise<ИтогНарезки> {
  const { длительность, onProgress } = параметры;
  const отменено = параметры.отменено ?? (() => false);
  const fps = параметры.fps > 1 ? параметры.fps : 30;
  const w0 = video.videoWidth || 640;
  const h0 = video.videoHeight || 360;
  const w = ШИРИНА;
  const h = Math.max(8, Math.round((h0 * w) / w0));
  const canvas = makeCanvas(w, h);

  /*  Длинный ролик режем тем же шагом, но предупреждаем: за минуту
      частый проход становится долгим.                               */
  const шаг = 1 / ВЫБОРОК_В_СЕКУНДУ;
  const всего = Math.max(2, Math.floor(длительность / шаг));

  const замеры: ЗамерКадра[] = [];
  let прежний: Снимок | null = null;
  for (let i = 0; i < всего; i += 1) {
    if (отменено()) throw new Error("отменено");
    const t = Math.min(длительность - 0.02, i * шаг);
    const { замер, снимок } = await замерить(video, t, canvas, w, h, прежний);
    замеры.push(замер);
    прежний = снимок;
    onProgress?.((i + 1) / всего, `Ищем склейки… ${Math.round(((i + 1) / всего) * 100)}%`);
  }

  // ---- где искать стыки ----
  /*  Порог адаптивный, как в общем разборе, но считается по спокойной
      части ролика. Если брать все кадры подряд, сами склейки задирают
      среднее и разброс — и на ролике с четырьмя склейками порог
      вырастает выше них же: находилась одна вместо четырёх.        */
  const разницы = замеры.slice(1).map((з) => з.разница);
  const спокойные = [...разницы].sort((a, b) => a - b).slice(0, Math.max(2, Math.floor(разницы.length * 0.8)));
  const порог = Math.max(0.11, среднее(спокойные) + 2.4 * разброс(спокойные));

  /*  Соседние выборки выше порога — это один и тот же стык, растянутый
      наплывом. Собираем их в группы, чтобы не плодить сцены-обрывки. */
  const группы: number[][] = [];
  for (let i = 1; i < замеры.length; i += 1) {
    if (замеры[i].разница <= порог) continue;
    const последняя = группы[группы.length - 1];
    if (последняя && i - последняя[последняя.length - 1] <= 1) последняя.push(i);
    else группы.push([i]);
  }

  // ---- уточнение до кадра ----
  const кадр = 1 / fps;
  const стыки: Array<{ время: number; окно: ЗамерКадра[] }> = [];
  for (let g = 0; g < группы.length; g += 1) {
    if (отменено()) throw new Error("отменено");
    const группа = группы[g];
    const слева = замеры[Math.max(0, группа[0] - 1)].t;
    const справа = замеры[Math.min(замеры.length - 1, группа[группа.length - 1] + 1)].t;
    onProgress?.(
      1,
      `Уточняем склейку ${g + 1} из ${группы.length}…`,
    );

    const окно: ЗамерКадра[] = [];
    let предыдущий: Снимок | null = null;
    for (let t = Math.max(0, слева - кадр); t <= Math.min(длительность - 0.02, справа + кадр); t += кадр) {
      const { замер, снимок } = await замерить(video, t, canvas, w, h, предыдущий);
      окно.push(замер);
      предыдущий = снимок;
      if (окно.length > 48) break;
    }
    if (окно.length < 2) continue;

    /*  Стык — там, где разница между соседними кадрами наибольшая.
        Границей считаем начало нового кадра, а не конец старого.     */
    let лучший = 1;
    for (let i = 2; i < окно.length; i += 1) {
      if (окно[i].разница > окно[лучший].разница) лучший = i;
    }
    стыки.push({ время: Number(окно[лучший].t.toFixed(3)), окно });
  }

  // ---- сцены ----
  let границы = [0, ...стыки.map((с) => с.время), длительность];
  границы = границы.filter((в, i, все) => i === 0 || в > все[i - 1] + 0.001);

  /*  Сцены короче 0,3 сек — это мерцание на стыке, а не сцена:
      приклеиваем их к соседней.                                      */
  const оставшиеся: number[] = [границы[0]];
  for (let i = 1; i < границы.length - 1; i += 1) {
    if (границы[i] - оставшиеся[оставшиеся.length - 1] >= САМАЯ_КОРОТКАЯ_СЦЕНА) {
      оставшиеся.push(границы[i]);
    }
  }
  оставшиеся.push(границы[границы.length - 1]);
  if (
    оставшиеся.length > 2 &&
    оставшиеся[оставшиеся.length - 1] - оставшиеся[оставшиеся.length - 2] < САМАЯ_КОРОТКАЯ_СЦЕНА
  ) {
    оставшиеся.splice(оставшиеся.length - 2, 1);
  }

  const сцены: СыраяСцена[] = [];
  for (let i = 0; i < оставшиеся.length - 1; i += 1) {
    const начало = оставшиеся[i];
    const конец = оставшиеся[i + 1];
    сцены.push({
      начало: Number(начало.toFixed(3)),
      конец: Number(конец.toFixed(3)),
      замеры: замеры.filter((з) => з.t >= начало && з.t < конец),
    });
  }
  if (!сцены.length) {
    сцены.push({ начало: 0, конец: Number(длительность.toFixed(3)), замеры });
  }

  // ---- переходы ----
  const фон = среднее(замеры.map((з) => з.детализация));
  const переходы: Переход[] = [];
  for (let i = 0; i < сцены.length - 1; i += 1) {
    const стык = сцены[i].конец;
    const нашли = стыки.reduce<{ время: number; окно: ЗамерКадра[] } | null>(
      (лучший, с) =>
        !лучший || Math.abs(с.время - стык) < Math.abs(лучший.время - стык) ? с : лучший,
      null,
    );
    const окно = нашли && Math.abs(нашли.время - стык) < 0.2 ? нашли.окно : [];
    const вид = определитьПереход(окно, стык, фон);
    переходы.push({
      вид: вид.вид,
      время: стык,
      длительность: вид.длительность,
      проверьте: вид.проверьте,
    });
  }

  return { сцены, переходы, порог: Number(порог.toFixed(4)), выборок: замеры.length };
}
