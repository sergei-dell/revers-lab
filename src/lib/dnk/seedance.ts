import {
  безКодовЦвета,
  камераПоАнглийски,
  планПоАнглийски,
  светПоАнглийски,
  сБольшой,
  ПЕРЕХОД_EN,
} from "@/lib/dnk/словарь";
import type { ДНК, СлотСцены, СценаДНК } from "@/lib/dnk/types";

/*  ЧТО ОТДАЁМ В SEEDANCE.

    Владелец генерирует сцены руками, на сайте Seedance. Ему нужно
    ровно три вещи: какие картинки загрузить и в каком порядке, какой
    текст вставить и какую длительность выставить. Всё это собирается
    кодом из уже готовой ДНК — нейросеть здесь не нужна.

    Номера картинок в тексте обязаны совпадать с порядком загрузки,
    поэтому список и текст строит один и тот же код.                */

/** Как владелец заводит сцену в Seedance. */
export type РежимКадров = "кадры" | "образцы";
export type ЯзыкТекста = "en" | "ru";

export type ВидКартинки = "первый" | "последний" | "герой" | "товар" | "место";

export type КартинкаДляЗагрузки = {
  вид: ВидКартинки;
  /** Подпись в списке. */
  имя: string;
  /** Что именно грузить: имя файла из архива или «ваше фото …». */
  файл: string;
  /** Кадр из нарезки можно скачать прямо отсюда. */
  скачиваемый: boolean;
};

const ИМЕНА_КАРТИНОК: Record<ВидКартинки, { имя: string; файл: (n: number) => string }> = {
  "первый": { имя: "Первый кадр", файл: (n) => `s${n}_first.jpg` },
  "последний": { имя: "Последний кадр", файл: (n) => `s${n}_last.jpg` },
  "герой": { имя: "Фото героя", файл: () => "ваше фото героя" },
  "товар": { имя: "Фото товара", файл: () => "ваше фото товара" },
  "место": { имя: "Фото места", файл: () => "ваше фото места" },
};

/*  ПОРЯДОК ЗАГРУЗКИ. Сначала два кадра сцены (если работаем кадрами),
    потом фото по включённым меткам — герой, товар, место.          */
export function порядокКартинок(
  сцена: СценаДНК,
  режим: РежимКадров,
  номер: number,
): КартинкаДляЗагрузки[] {
  const список: ВидКартинки[] = [];
  if (режим === "кадры") список.push("первый", "последний");
  for (const слот of ["герой", "товар", "место"] as СлотСцены[]) {
    if (сцена.слоты.includes(слот)) список.push(слот as ВидКартинки);
  }
  return список.map((вид) => ({
    вид,
    имя: ИМЕНА_КАРТИНОК[вид].имя,
    файл: ИМЕНА_КАРТИНОК[вид].файл(номер),
    скачиваемый: вид === "первый" || вид === "последний",
  }));
}

/*  Если действия нет, в тексте остаётся заметная дыра: лучше увидеть
    её глазами, чем отправить в генерацию полуфразу.                */
const НЕТ_ДЕЙСТВИЯ = "[опишите действие]";

function секунды(сцена: СценаДНК): string {
  return (сцена.конец - сцена.начало).toFixed(1);
}

export function текстСцены(
  сцена: СценаДНК,
  настройки: { режим: РежимКадров; язык: ЯзыкТекста; номер: number },
): string {
  const { режим, язык, номер } = настройки;
  const картинки = порядокКартинок(сцена, режим, номер);
  const номерКартинки = (вид: ВидКартинки) =>
    картинки.findIndex((к) => к.вид === вид) + 1;
  const длина = секунды(сцена);
  const есть = (слот: СлотСцены) => сцена.слоты.includes(слот);
  const части: string[] = [];

  if (язык === "en") {
    const вступление = [
      планПоАнглийски(сцена.гены.план),
      камераПоАнглийски(сцена.гены.камера),
      светПоАнглийски(сцена.гены.свет),
    ].filter(Boolean);
    части.push(
      `Scene ${номер}, ${длина} seconds.` +
        (вступление.length ? ` ${сБольшой(вступление.join(", "))}.` : ""),
    );

    /*  Английской фразы может не быть — тогда идёт русская: Seedance
        её поймёт хуже, но это честнее пустой строки.               */
    const действие = сцена.гены.действиеEn.trim() || сцена.гены.действие.trim() || НЕТ_ДЕЙСТВИЯ;
    const кто: string[] = [];
    if (есть("герой")) кто.push(`the person from image ${номерКартинки("герой")}`);
    if (есть("товар")) кто.push(`the product from image ${номерКартинки("товар")}`);
    части.push(`${действие}.${кто.length ? ` In frame: ${кто.join(" with ")}.` : ""}`);

    if (есть("место")) части.push(`Location: the place from image ${номерКартинки("место")}.`);

    части.push(
      режим === "кадры"
        ? `Start exactly from image ${номерКартинки("первый")} and end exactly on image ${номерКартинки(
            "последний",
          )}. Keep composition and camera movement as in these frames.`
        : "Keep the product shape, colors and proportions exactly as in the reference.",
    );
    части.push("No text, no logos, no new objects. Do not change the scene.");
    return части.join("\n");
  }

  const вступление = [сцена.гены.план, сцена.гены.камера, безКодовЦвета(сцена.гены.свет)].filter(
    Boolean,
  );
  части.push(
    `Сцена ${номер}, ${длина} сек.` +
      (вступление.length ? ` ${сБольшой(вступление.join(", "))}.` : ""),
  );

  const действие = сцена.гены.действие.trim() || НЕТ_ДЕЙСТВИЯ;
  const кто: string[] = [];
  if (есть("герой")) кто.push(`человек с картинки ${номерКартинки("герой")}`);
  if (есть("товар")) кто.push(`товар с картинки ${номерКартинки("товар")}`);
  части.push(`${действие}.${кто.length ? ` В кадре: ${кто.join(" и ")}.` : ""}`);

  if (есть("место")) части.push(`Место: как на картинке ${номерКартинки("место")}.`);

  части.push(
    режим === "кадры"
      ? `Начать точно с картинки ${номерКартинки("первый")}, закончить точно на картинке ${номерКартинки(
          "последний",
        )}. Композицию и движение камеры не менять.`
      : "Форму, цвет и пропорции товара сохранить как на образце.",
  );
  части.push("Без надписей и логотипов, без новых предметов.");
  return части.join("\n");
}

/*  ПЛАН МОНТАЖА простым текстом: его вставляют в заметки и склеивают
    по нему ролик в любом редакторе.                                */
export function планМонтажа(днк: ДНК): string {
  const строки: string[] = [];
  днк.сцены.forEach((с, i) => {
    const готово = с.сгенерирована ? " ✓" : "";
    строки.push(`${i + 1}. ${с.имя} — s${i + 1}.mp4 — ${секунды(с)} с${готово}`);
    const переход = днк.переходы[i];
    if (переход) {
      const длина =
        переход.длительность > 0 ? ` · ${переход.длительность.toFixed(1).replace(".", ",")} с` : "";
      строки.push(`   ↓ ${переход.вид}${длина}`);
    }
  });
  const всего = днк.сцены.reduce((a, с) => a + (с.конец - с.начало), 0);
  const готовых = днк.сцены.filter((с) => с.сгенерирована).length;
  строки.push("");
  строки.push(
    `${готовых} из ${днк.сцены.length} сцен готово · общая длительность ${всего.toFixed(1)} с`,
  );
  return строки.join("\n");
}

/*  ФАЙЛ `seedance.txt` В АРХИВЕ. Нужен, чтобы можно было работать,
    открыв только архив: ни сайта, ни истории разборов под рукой.   */
export function файлSeedance(днк: ДНК, режим: РежимКадров = "кадры"): string {
  const куски: string[] = [];
  куски.push(`ДЛЯ SEEDANCE · ${днк.источник}`);
  куски.push(
    `${днк.сцены.length} сцен · ${днк.длительность.toFixed(1)} сек · ${днк.ширина}×${днк.высота}`,
  );
  куски.push(
    режим === "кадры"
      ? "Режим: первый и последний кадр сцены."
      : "Режим: по образцам, без кадров сцены.",
  );
  куски.push("");

  днк.сцены.forEach((с, i) => {
    const номер = i + 1;
    куски.push(`${"=".repeat(60)}`);
    куски.push(`СЦЕНА ${номер} · ${с.имя} · ${секунды(с)} сек`);
    куски.push("");
    куски.push("Загрузите картинки в этом порядке:");
    порядокКартинок(с, режим, номер).forEach((к, j) => {
      куски.push(`  ${j + 1}. ${к.имя} — ${к.файл}`);
    });
    куски.push("");
    куски.push("Текст (EN):");
    куски.push(текстСцены(с, { режим, язык: "en", номер }));
    куски.push("");
    куски.push("Текст (RU):");
    куски.push(текстСцены(с, { режим, язык: "ru", номер }));
    куски.push("");
    куски.push(`Длительность в Seedance: ${секунды(с)} с`);
    const переход = днк.переходы[i];
    if (переход) {
      куски.push(
        `Переход к следующей сцене: ${переход.вид} (${ПЕРЕХОД_EN[переход.вид]})` +
          (переход.длительность > 0 ? `, ${переход.длительность.toFixed(2)} с` : ""),
      );
    }
    куски.push("");
  });

  куски.push(`${"=".repeat(60)}`);
  куски.push("ПЛАН МОНТАЖА");
  куски.push("");
  куски.push(планМонтажа(днк));
  return куски.join("\n");
}
