// ЧЁРНЫЕ ПОЛЯ ВОКРУГ КАРТИНКИ.
//
// Вертикальный ролик часто лежит внутри широкого файла: картинка узкая,
// а слева и справа чернота. По размеру файла тогда выходит 16:9 или 4:3,
// хотя снято вертикально — и генератор получает не тот формат.
//
// Здесь поля меряются по самим пикселям: с каждой стороны отсекаются
// ряды и столбцы, которые сплошь тёмные и без деталей. Считается это на
// маленьком кадре разбора, поэтому почти ничего не стоит.

export type Рамка = { x0: number; y0: number; x1: number; y1: number };

// Насколько тёмным должен быть ряд, чтобы считаться полем.
const ПРЕДЕЛ_СРЕДНЕЙ = 14;
const ПРЕДЕЛ_ЯРКОЙ_ТОЧКИ = 42;
// Больше половины кадра полями не бывает: это уже затемнение, а не рамка.
const МАКСИМУМ_ДОЛИ = 0.45;

function яркость(data: Uint8ClampedArray, p: number): number {
  return (data[p] * 0.2126 + data[p + 1] * 0.7152 + data[p + 2] * 0.0722);
}

function рядТёмный(data: Uint8ClampedArray, w: number, y: number): boolean {
  let сумма = 0;
  let макс = 0;
  for (let x = 0; x < w; x += 1) {
    const l = яркость(data, (y * w + x) * 4);
    сумма += l;
    if (l > макс) макс = l;
  }
  return сумма / w < ПРЕДЕЛ_СРЕДНЕЙ && макс < ПРЕДЕЛ_ЯРКОЙ_ТОЧКИ;
}

function столбецТёмный(data: Uint8ClampedArray, w: number, h: number, x: number): boolean {
  let сумма = 0;
  let макс = 0;
  for (let y = 0; y < h; y += 1) {
    const l = яркость(data, (y * w + x) * 4);
    сумма += l;
    if (l > макс) макс = l;
  }
  return сумма / h < ПРЕДЕЛ_СРЕДНЕЙ && макс < ПРЕДЕЛ_ЯРКОЙ_ТОЧКИ;
}

/** Где в кадре сама картинка. Возвращает границы в пикселях этого кадра. */
export function рамкаКартинки(data: Uint8ClampedArray, w: number, h: number): Рамка {
  let y0 = 0;
  let y1 = h - 1;
  let x0 = 0;
  let x1 = w - 1;
  const пределВысоты = Math.floor(h * МАКСИМУМ_ДОЛИ);
  const пределШирины = Math.floor(w * МАКСИМУМ_ДОЛИ);
  while (y0 < пределВысоты && рядТёмный(data, w, y0)) y0 += 1;
  while (y1 > h - 1 - пределВысоты && рядТёмный(data, w, y1)) y1 -= 1;
  while (x0 < пределШирины && столбецТёмный(data, w, h, x0)) x0 += 1;
  while (x1 > w - 1 - пределШирины && столбецТёмный(data, w, h, x1)) x1 -= 1;
  if (x1 <= x0 || y1 <= y0) return { x0: 0, y0: 0, x1: w - 1, y1: h - 1 };
  return { x0, y0, x1, y1 };
}

function медиана(значения: number[]): number {
  if (!значения.length) return 0;
  const ряд = [...значения].sort((a, b) => a - b);
  return ряд[Math.floor(ряд.length / 2)];
}

/*  Собственный размер картинки по всем снятым кадрам. Берётся медиана, а
    не максимум: затемнение в начале ролика или тёмный план не должны
    выдавать себя за поля.                                             */
export function размерКартинки(
  рамки: Рамка[],
  w: number,
  h: number,
): { width: number; height: number; поля: "нет" | "по бокам" | "сверху и снизу" } {
  if (!рамки.length) return { width: w, height: h, поля: "нет" };
  const слева = медиана(рамки.map((р) => р.x0));
  const справа = медиана(рамки.map((р) => w - 1 - р.x1));
  const сверху = медиана(рамки.map((р) => р.y0));
  const снизу = медиана(рамки.map((р) => h - 1 - р.y1));
  // Поле меньше полутора процентов стороны — это кромка кодека, не рамка.
  const порогШирины = Math.max(1, w * 0.015);
  const порогВысоты = Math.max(1, h * 0.015);
  const боковые = слева + справа > порогШирины * 2;
  const верхние = сверху + снизу > порогВысоты * 2;
  const width = боковые ? Math.max(1, w - слева - справа) : w;
  const height = верхние ? Math.max(1, h - сверху - снизу) : h;
  return {
    width,
    height,
    поля: боковые && !верхние ? "по бокам" : верхние && !боковые ? "сверху и снизу" : боковые && верхние ? "по бокам" : "нет",
  };
}
